class SuitcaseMemory:
    """Ό,τι ξέρουμε για ΜΙΑ βαλίτσα: 6D pose, ποιες πλευρές ελέγχθηκαν,
    τι είδαμε σε καθεμία, πού είναι τα ροδάκια και το απλό χερούλι.

    ΚΡΙΣΙΜΟ: οι πλευρές αποθηκεύονται ΣΧΕΤΙΚΑ με τον άξονα της βαλίτσας
    (τοπική γωνία), ΟΧΙ σε απόλυτες γωνίες βάσης. Η βαλίτσα προχωράει και
    γυρίζει πάνω στην ταινία: μια απόλυτη γωνία «ελέγχθηκε» δείχνει άλλη
    πλευρά μέσα σε δευτερόλεπτα. Το ίδιο σφάλμα είχε και η παλιά
    tried_angles - γι' αυτό ξαναέψαχνε εκεί που είχε ήδη κοιτάξει.
    """

    def __init__(self, bid):
        """Άδεια μνήμη για τη βαλίτσα με id σώματος bid."""
        self.bid = bid
        self.pos = None            # τελευταία γνωστή θέση (x, y, z)
        self.yaw = 0.0             # στροφή γύρω από z
        self.t = 0.0               # πότε ενημερώθηκε το pose
        self.sides = []            # πλευρές που ελέγχθηκαν
        self.wheel_loc = None      # τοπική γωνία προς τα ροδάκια
        self.plain_loc = None      # τοπική γωνία προς το ΑΠΛΟ χερούλι
        self.flags = set()         # εφάπαξ μηνύματα
        self.q = None              # πλήρης προσανατολισμός (6D) του body tag
        self.wheel_src = ''        # από πού ξέρουμε την κατεύθυνση ροδακιών
        self.one_wheel = None      # (τοπική γωνία, θέση) ΕΝΟΣ ορατού ροδακιού
        self.wide_done = False     # έγινε ήδη το ευρύ πλάνο για τα ροδάκια
        self.approach_done = False # έγινε ήδη το πλησίασμα για το 2ο ροδάκι

    # ---------- pose ----------
    def update(self, pos, yaw, now, q=None):
        """Νέα θέαση του body tag -> ενημέρωση του 6D pose στη μνήμη.

        ΔΕΝ σβήνει τίποτα: πλευρές και ροδάκια είναι σε ΤΟΠΙΚΕΣ γωνίες, άρα
        ισχύουν και αφού η βαλίτσα μετακινηθεί ή γυρίσει.
        Επιστρέφει True αν μετακινήθηκε > MOVED_RESET (μόνο για το log).
        """
        moved = self.pos is not None and math.dist(self.pos, pos) > MOVED_RESET
        self.pos, self.yaw, self.t = pos, yaw, now
        if q is not None:
            self.q = q
        return moved

    # ---------- μετατροπές γωνίας ----------
    def loc(self, a):
        """απόλυτη -> τοπική (ως προς τον άξονα της βαλίτσας)"""
        return (a - self.yaw + math.pi) % (2*math.pi) - math.pi

    def absol(self, l):
        """τοπική -> απόλυτη, με τη ΣΗΜΕΡΙΝΗ στροφή της βαλίτσας"""
        return l + self.yaw

    # ---------- πλευρές ----------
    def find(self, a):
        """Η καταγεγραμμένη πλευρά κοντά (< ANGLE_SAME) στην απόλυτη γωνία a, ή None."""
        l = self.loc(a)
        for sd in self.sides:
            if ang_diff(l, sd['loc']) < ANGLE_SAME:
                return sd
        return None

    def _side(self, a, label, now):
        """Η πλευρά στη γωνία a - τη δημιουργεί αν δεν υπάρχει.

        Πεδία μιας πλευράς (dict):
            loc      τοπική γωνία (ως προς τον άξονα της βαλίτσας)
            label    περιγραφή για το log         t     τελευταία ενημέρωση
            saw      ids που είδαμε από εκεί       visited  πήγαμε εκεί
            fails    πόσες φορές δεν φτάστηκε      plain    εκεί είναι το ΑΠΛΟ
            refine / peek   μικρές διορθώσεις που έγιναν / ποια ματιά ακολουθεί
        """
        sd = self.find(a)
        if sd is None:
            sd = {'loc': self.loc(a), 'label': label, 't': now,
                  'saw': set(), 'refine': 0, 'peek': 0,
                  'visited': False, 'fails': 0, 'plain': False}
            self.sides.append(sd)
        return sd

    def mark(self, a, label, now):
        """Καταγράφει ότι ΠΗΓΑΜΕ σε αυτή την πλευρά."""
        sd = self._side(a, label, now)
        sd['visited'], sd['t'] = True, now
        return sd

    def fail(self, a, label, now):
        """Η πλευρά ΔΕΝ φτάστηκε αυτή τη φορά. Επιστρέφει πόσες φορές."""
        sd = self._side(a, label, now)
        sd['fails'] += 1
        sd['t'] = now
        return sd['fails']

    def plain_at(self, a, now):
        """Εδώ είναι το ΑΠΛΟ χερούλι -> η πλευρά αποκλείεται ΜΟΝΙΜΑ."""
        sd = self._side(a, 'ΑΠΛΟ χερούλι', now)
        new = not sd['plain']
        sd['plain'], sd['t'] = True, now
        return new

    def done_side(self, a):
        """Ελεγμένη πλευρά: επισκέφθηκε, ή έχει το απλό, ή είναι ανέφικτη."""
        sd = self.find(a)
        return sd is not None and (sd['visited'] or sd['plain']
                                   or sd['fails'] >= SIDE_MAX_FAILS)

    def saw(self, a, ids, now):
        """Καταγράφει ΤΙ είδαμε από αυτή την πλευρά."""
        sd = self.find(a)
        if sd is not None and ids:
            sd['saw'].update(ids)
            sd['t'] = now

    def reset_search(self):
        """Νέα αναζήτηση από την αρχή (π.χ. όταν τελείωσε αυτή η βαλίτσα).
        Pose και ροδάκια ΜΕΝΟΥΝ - ισχύουν ακόμα."""
        self.sides = []
        self.flags.clear()
        self.wide_done = self.approach_done = False

    # ---------- αναφορά ----------
    def report(self, now):
        """Γραμμές για το log: pose, ροδάκια, απλό χερούλι, κατάσταση κάθε πλευράς."""
        out = [f"  [ΜΝΗΜΗ] {nice(self.bid)}"]
        if self.pos:
            out.append(f"     6D pose: ({self.pos[0]:.2f}, {self.pos[1]:.2f}, "
                       f"{self.pos[2]:.2f}) m  στροφή {math.degrees(self.yaw):+.0f}°"
                       f"  [πριν {now-self.t:.1f}s]")
        if self.wheel_loc is not None:
            out.append(f"     ροδάκια: τοπικά {math.degrees(self.wheel_loc):+.0f}°"
                       f"  (τώρα απόλυτα {math.degrees(self.absol(self.wheel_loc)):+.0f}°)"
                       f"  [{self.wheel_src}]")
        else:
            out.append(f"     ροδάκια: άγνωστα  (ευρύ πλάνο: "
                       f"{'έγινε' if self.wide_done else 'όχι ακόμα'}, πλησίασμα: "
                       f"{'έγινε' if self.approach_done else 'όχι'})")
        if self.plain_loc is not None:
            out.append(f"     απλό χερούλι: τοπικά {math.degrees(self.plain_loc):+.0f}°")
        if not self.sides:
            out.append("     πλευρές που ελέγχθηκαν: καμία ακόμα")
        else:
            out.append(f"     πλευρές που ελέγχθηκαν: {len(self.sides)}")
            for sd in sorted(self.sides, key=lambda x: x['loc']):
                saw = (nice_list(sorted(sd['saw'])) if sd['saw'] else 'τίποτα')
                st = ('ΑΠΛΟ - αποκλεισμένη' if sd['plain'] else
                      'ελέγχθηκε' if sd['visited'] else
                      f"ΑΝΕΦΙΚΤΗ ({sd['fails']})" if sd['fails'] >= SIDE_MAX_FAILS
                      else f"απέτυχε {sd['fails']}/{SIDE_MAX_FAILS}")
                out.append(f"       τοπικά {math.degrees(sd['loc']):+4.0f}° "
                           f"(τώρα {math.degrees(self.absol(sd['loc'])):+4.0f}°) "
                           f"{sd['label'][:28]:28s} [{st}] -> είδε: {saw}"
                           f"   [διορθώσεις {sd['refine']}/{REFINE_MAX}, "
                           f"πριν {now-sd['t']:.0f}s]")
        return out


