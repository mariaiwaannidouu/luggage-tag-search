def load_robot_config(path):
    """Διαβάζει το YAML του βραχίονα και αντικαθιστά τις αντίστοιχες
    σταθερές. Επιστρέφει το όνομα του βραχίονα (κλειδί robot_name)."""
    import yaml
    with open(path, encoding='utf-8') as f:
        cfg = yaml.safe_load(f) or {}
    unknown = [k for k in cfg if k not in ROBOT_CONFIG_KEYS and k != 'robot_name']
    if unknown:
        raise ValueError(f"άγνωστα κλειδιά στο {path}: {unknown} - επιτρέπονται: "
                         f"{sorted(ROBOT_CONFIG_KEYS)} + robot_name")
    g = globals()
    for key, (name, conv) in ROBOT_CONFIG_KEYS.items():
        if key in cfg:
            g[name] = conv(cfg[key])
    # παράγωγη τιμή: κάθετο οπτικό πεδίο από το οριζόντιο και την ανάλυση
    g['CAM_VFOV'] = 2.0*math.atan(math.tan(CAM_HFOV/2.0) * CAM_H / CAM_W)
    return str(cfg.get('robot_name', path))


def resolve_robot_config(node):
    """Πού είναι το YAML: παράμετρος ROS 'robot_config', αλλιώς η μεταβλητή
    περιβάλλοντος ROBOT_CONFIG. Κενό = προεπιλογές UR5e αυτού του αρχείου."""
    path = ''
    try:
        node.declare_parameter('robot_config', '')
        path = node.get_parameter('robot_config').get_parameter_value().string_value
    except Exception:
        path = ''
    return path or os.environ.get('ROBOT_CONFIG', '')


