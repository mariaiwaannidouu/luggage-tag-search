def main(args=None):
    """Σημείο εκκίνησης: ROS, ρυθμίσεις βραχίονα (YAML ή UR5e), MoveItPy, βρόχος.

    Ctrl+C -> έξοδος. Το os._exit(0) κλείνει αμέσως (το MoveItPy μερικές φορές
    κρατά νήματα ανοιχτά και το πρόγραμμα δεν τερματίζει αλλιώς).
    """
    rclpy.init(args=args)
    listener = TagListener()
    # Ρυθμίσεις βραχίονα: YAML αν δόθηκε, αλλιώς οι προεπιλογές UR5e.
    cfg_path = resolve_robot_config(listener)
    if cfg_path:
        name = load_robot_config(cfg_path)
        print(f"=== Ρυθμίσεις βραχίονα: {name}  ({cfg_path}) ===", flush=True)
    else:
        print("=== Ρυθμίσεις βραχίονα: προεπιλογές UR5e (χωρίς robot_config) ===",
              flush=True)
    for _l in robot_config_summary():
        print(_l, flush=True)
    ur5e = MoveItPy(node_name='move_arm3_controller')
    arm = ur5e.get_planning_component(PLANNING_GROUP)
    print("=== Αναζήτηση χερουλιού v2 (Ctrl+C) ===", flush=True)
    try:
        Mission(ur5e, arm, listener).run()
    except KeyboardInterrupt:
        pass
    sys.stdout.flush()
    os._exit(0)


if __name__ == '__main__':
    main()
