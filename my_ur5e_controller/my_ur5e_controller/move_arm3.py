class Mission:
    """Η λογική αναζήτησης: ένας κύκλος = παρατήρηση + ΜΙΑ ενέργεια (δες run).

    ur5e / arm : MoveItPy και planning component    listener : TagListener
    Κυριότερη κατάσταση (όλη στο __init__):
        target        βαλίτσα που ψάχνουμε τώρα (id σώματος) ή None
        mem           id -> SuitcaseMemory
        done_bodies   id -> κύκλος που τελείωσε (αγνοείται για DONE_CYCLES)
        handle_pos    θέση του tag προορισμού όσο το παρακολουθούμε
        watch_mode    'forward' / 'right' - ποια επιτήρηση
        boxes         βαλίτσες για τον έλεγχο «πολύ κοντά» στο move_to
    """
    def __init__(self, ur5e, arm, listener):
        """Αρχική κατάσταση. Κάθε πεδίο εξηγείται δίπλα του."""
        self.ur5e, self.arm, self.listener = ur5e, arm, listener
        # yaws/quats: τελευταίος προσανατολισμός κάθε tag (μένει κι όταν δεν φαίνεται)
        # hist: τελευταίες θέσεις ανά tag (για ταχύτητα)
        self.yaws, self.hist = {}, {}
        self.quats = {}
        # στόχος-βαλίτσα και πότε φάνηκε τελευταία (για LOST_GRACE)
        self.target, self.last_seen = None, 0.0
        # tag προορισμού που παρακολουθούμε: θέση, πρώτη θέαση, κάθετος (αζιμούθιο)
        self.handle_pos, self.handle_first_t = None, 0.0
        self.handle_yaw = None
        # relook: πόσες μικρές διορθώσεις αφού χάθηκε
        self.relook = 0
        self.glimpse = {}                              # tags 1 καρέ
        self.relook_st = {'refine': 0, 'peek': 0}      # μικρές διορθώσεις tag
        self.dest_cycles, self.dest_fixed = 0, False   # παραμονή στον προορισμό
        self.done_bodies, self.done_handles = {}, []   # -> κύκλος που τελείωσαν
        self.cycle = 0
        self.boxes = {}          # bid -> (θέση, στροφή) γνωστών βαλιτσών (ασφάλεια)
        self.mem = {}                 # bid -> SuitcaseMemory (πλήρης μνήμη)
        # προειδοποιήσεις που τυπώνονται ΜΙΑ φορά (για να μη γεμίζει το log)
        self.ik_warned, self.occl_warned = False, False
        self.seed_warned, self.goal_warned = False, False
        self.occl_note = ''
        # μνήμη «είδαμε τον προορισμό στο πέρασμα» (μόνο όσο κρατά η αναζήτηση)
        self.dest_seen, self.dest_tries = None, 0
        # εμπόδια MoveIt: πότε φάνηκε κάθε βαλίτσα / αν μπήκε το δάπεδο
        self.co_seen, self.ground_done = {}, False
        # επιτήρηση: 'forward' ή 'right'
        self.watch_mode = 'forward'
        self.blind_cycles = 0         # κύκλοι χωρίς αξιοποιήσιμη βαλίτσα
        self.in_watch = False         # είμαστε ήδη σε θέση επιτήρησης
        self.stuck = 0                # κύκλοι χωρίς καμία κίνηση
        # Πόσες υποψήφιες πόζες απορρίφθηκαν σε ΑΥΤΟΝ τον κύκλο και γιατί.
        # Τυπώνονται στο τέλος κάθε κύκλου: μια σιωπηλή απόρριψη είναι
        # ακριβώς το είδος σφάλματος που κρύβεται για μέρες.
        self.rej_reach, self.rej_occl, self.rej_ik, self.rej_plan = 0, 0, 0, 0
        self.rej_clear = 0
        # Ποια βαλίτσα είδαμε τελευταία και πότε. Χρειάζεται για να ξέρουμε
        # τους ΡΟΛΟΥΣ των χερουλιών όταν η βαλίτσα βγει στιγμιαία εκτός
        # κάδρου (συμβαίνει συχνά καθώς ο βραχίονας πλησιάζει ένα χερούλι).
        self.last_body, self.last_body_t = None, 0.0

    # ---------- αισθητήρας ----------
    def observe(self, seconds=OBSERVE_TIME):
        """Συλλέγει ανιχνεύσεις για `seconds` και επιστρέφει id -> διάμεση θέση.

        Tag που φάνηκε σε 1 μόνο καρέ ΔΕΝ μπαίνει (αναξιόπιστη θέση) - εκτός από
        το tag ΠΡΟΟΡΙΣΜΟΥ, που μετράει ως «βρέθηκε» ακόμα και σε 1 καρέ.
        Ενημερώνει επίσης yaws/quats και το ιστορικό θέσεων (για την ταχύτητα).
        """
        end = time.time() + seconds
        acc = {}
        while time.time() < end:
            rclpy.spin_once(self.listener, timeout_sec=0.05)
            for mid, pos in self.listener.detections.items():
                acc.setdefault(mid, []).append(pos)
            self.yaws.update(self.listener.yaws)
            self.quats.update(self.listener.quats)
        out, now = {}, time.time()
        # Tags που φάνηκαν ΜΟΝΟ σε 1 καρέ: δεν μπαίνουν στις ανιχνεύσεις
        # (αναξιόπιστη θέση), αλλά λένε ότι «κάτι είδαμε εδώ» -> αξίζει διόρθωση.
        self.glimpse = {}
        for mid, pl in acc.items():
            # Το tag ΠΡΟΟΡΙΣΜΟΥ μετράει ως «βρέθηκε» ακόμα και σε 1 καρέ: αν
            # φάνηκε, η αναζήτηση ΣΤΑΜΑΤΑ εκεί (αναγνωρίζεται μονοσήμαντα από το id).
            if len(pl) < 2 and mid != DEST_ID:
                self.glimpse[mid] = pl[0]
                continue
            n = len(pl)
            med = (sorted(p[0] for p in pl)[n//2],
                   sorted(p[1] for p in pl)[n//2],
                   sorted(p[2] for p in pl)[n//2])
            out[mid] = med
            h = self.hist.setdefault(mid, [])
            h.append((now, med))
            if len(h) > 6:
                h.pop(0)
        return out

    def velocity(self, bid):
        """Ταχύτητα (vx, vy) σε m/s από το ιστορικό θέσεων, ή (0, 0)."""
        h = self.hist.get(bid, [])
        if len(h) < 3:
            return (0.0, 0.0)
        (t0, p0), (t1, p1) = h[0], h[-1]
        dt = t1 - t0
        if dt < 0.5:
            return (0.0, 0.0)
        return ((p1[0]-p0[0])/dt, (p1[1]-p0[1])/dt)

    # ---------- collision ----------
    def setup_ground(self):
        """Βάζει το δάπεδο ως εμπόδιο στο MoveIt (μία φορά)."""
        if self.ground_done:
            return
        co = CollisionObject()
        co.header.frame_id = BASE_FRAME
        co.id = 'ground_plane'
        box = SolidPrimitive()
        box.type = SolidPrimitive.BOX
        box.dimensions = [4.0, 4.0, 0.02]
        pose = Pose()
        pose.position.z = -0.011
        pose.orientation.w = 1.0
        co.primitives.append(box)
        co.primitive_poses.append(pose)
        co.operation = CollisionObject.ADD
        for _ in range(3):
            self.listener.co_pub.publish(co)
            rclpy.spin_once(self.listener, timeout_sec=0.05)
        self.ground_done = True
        print("   [collision] δάπεδο -> /collision_object", flush=True)

    def update_collision(self, det, now):
        """Βάζει/ενημερώνει κάθε ορατή βαλίτσα ως κουτί-εμπόδιο στο MoveIt.

        Κουτί που δεν ενημερώθηκε για CO_TTL s σβήνεται - εκτός από τη βαλίτσα
        που ψάχνουμε από μνήμη (αλλιώς ο βραχίονας θα περνούσε μέσα της).
        """
        active = []
        for bid, pos in det.items():
            if bid not in BODY_IDS:
                continue
            L, W, H = BODY_IDS[bid]['dims']
            yaw = self.yaws.get(bid, 0.0)
            co = CollisionObject()
            co.header.frame_id = BASE_FRAME
            co.id = f'suitcase_{bid}'
            box = SolidPrimitive()
            box.type = SolidPrimitive.BOX
            box.dimensions = [L+CO_PAD, W+CO_PAD, H+CO_PAD]
            pose = Pose()
            pose.position.x = float(pos[0])
            pose.position.y = float(pos[1])
            pose.position.z = float(max(H/2.0, pos[2]-H/2.0))
            pose.orientation.z = math.sin(yaw/2.0)
            pose.orientation.w = math.cos(yaw/2.0)
            co.primitives.append(box)
            co.primitive_poses.append(pose)
            co.operation = CollisionObject.ADD
            self.listener.co_pub.publish(co)
            self.co_seen[bid] = now
            active.append(BODY_IDS[bid]['name'])

        for bid in list(self.co_seen):
            if now - self.co_seen[bid] > CO_TTL:
                # Η βαλίτσα που ψάχνουμε ΑΠΟ ΜΝΗΜΗ μένει εμπόδιο: αλλιώς ο
                # βραχίονας θα περνούσε μέσα της πηγαίνοντας στην άλλη πλευρά.
                if bid == self.target and self.known_pos(bid, {}, now) is not None:
                    continue
                co = CollisionObject()
                co.header.frame_id = BASE_FRAME
                co.id = f'suitcase_{bid}'
                co.operation = CollisionObject.REMOVE
                self.listener.co_pub.publish(co)
                del self.co_seen[bid]

        for _ in range(3):
            rclpy.spin_once(self.listener, timeout_sec=0.05)
        if active:
            print(f"   [collision] ενεργά: {', '.join(active)}", flush=True)

    # ---------- ασφάλεια ----------
    def clearance(self, cam, dims, pos, yaw):
        """Απόσταση κάμερας από το ΚΟΥΤΙ της βαλίτσας (0 = μέσα του).

        ΠΡΟΣΟΧΗ: pos είναι το body tag, στην ΚΟΡΥΦΗ. Το κέντρο του κουτιού είναι
        H/2 πιο κάτω (ίδιο με το κουτί του MoveIt). Παλιά το κουτί ήταν κεντραρισμένο
        στο tag, δηλαδή «φούσκωνε» H/2 ΠΑΝΩ από τη βαλίτσα: κάμερα ~15cm πάνω από
        την κορυφή έβγαινε ψευδώς «κίνδυνος σύγκρουσης».
        """
        L, W, H = dims
        cz = max(H/2.0, pos[2] - H/2.0)
        dx, dy, dz = cam[0]-pos[0], cam[1]-pos[1], cam[2]-cz
        c, s = math.cos(yaw), math.sin(yaw)
        lx, ly = dx*c + dy*s, -dx*s + dy*c
        qx = max(abs(lx)-L/2, 0.0)
        qy = max(abs(ly)-W/2, 0.0)
        qz = max(abs(dz)-H/2, 0.0)
        return math.sqrt(qx*qx + qy*qy + qz*qz)

    def collision_risk(self, det):
        """Κίνδυνος σύγκρουσης κάμερας-βαλίτσας; -> (bid, ταχύτητα, απόσταση τώρα,
        απόσταση σε PREDICT_T s) για τη χειρότερη βαλίτσα, ή None.
        """
        cam = self.listener.camera_position()
        if cam is None:
            return None
        worst = None
        for bid, pos in det.items():
            if bid not in BODY_IDS:
                continue
            dims = BODY_IDS[bid]['dims']
            yaw = self.yaws.get(bid, 0.0)
            cn = self.clearance(cam, dims, pos, yaw)
            vx, vy = self.velocity(bid)
            sp = math.hypot(vx, vy)
            pred = (pos[0]+vx*PREDICT_T, pos[1]+vy*PREDICT_T, pos[2])
            cp = self.clearance(cam, dims, pred, yaw)
            if cn < HARD_CLEARANCE or (sp > MOVING_SPEED and cp < SAFE_CLEARANCE
                                       and cp < cn):
                if worst is None or cp < worst[3]:
                    worst = (bid, sp, cn, cp)
        return worst

    # ---------- κίνηση ----------
    def self_occludes(self, rs, cam, look, axes):
        """Πόσο ΕΞΩ από το κάδρο μένει ο ίδιος ο βραχίονας;

        Επιστρέφει ΠΕΡΙΘΩΡΙΟ: το ελάχιστο, πάνω σε όλη την αλυσίδα των
        συνδέσμων, του λόγου «απόσταση από τον άξονα / μισό πλάτος κάδρου».
            < 1.0  -> κάποιος σύνδεσμος είναι ΜΕΣΑ στο κάδρο (φραγμένο)
            = 1.0  -> ακριβώς στην άκρη
            > 1.0  -> καθαρό· όσο μεγαλύτερο, τόσο πιο έξω
        None αν η FK δεν είναι διαθέσιμη.
        """
        try:
            pts = []
            for ln in SELF_LINKS:
                T = rs.get_global_link_transform(ln)
                pts.append((float(T[0][3]), float(T[1][3]), float(T[2][3])))
        except Exception as e:
            if not self.occl_warned:
                self.occl_warned = True
                print(f"   [!] έλεγχος αυτο-απόκρυψης ΑΝΕΝΕΡΓΟΣ "
                      f"({type(e).__name__}: {e}) - πέφτω στην ευρετική",
                      flush=True)
            return None

        # --- ΠΡΑΓΜΑΤΙΚΟΙ άξονες της κάμερας (από το quaternion) ---
        # Με ελεύθερο roll το κάδρο γυρίζει: το «δεξιά» και το «πάνω» δεν
        # προκύπτουν πια από τον παγκόσμιο άξονα z.
        vn = math.dist(cam, look)
        if vn < 1e-6:
            return 99.0
        (fx, fy, fz), (rx, ry, rz), (ux, uy, uz) = axes

        tx = math.tan(CAM_HFOV*0.5) * FRAME_CORE
        ty = math.tan(CAM_VFOV*0.5) * FRAME_CORE
        worst = 99.0

        for i in range(len(pts)-1):
            a, b = pts[i], pts[i+1]
            seg = math.dist(a, b)
            steps = max(2, int(seg / SELF_SAMPLE_STEP) + 1)
            for k in range(steps + 1):
                t = k / steps
                px = a[0] + (b[0]-a[0])*t
                py = a[1] + (b[1]-a[1])*t
                pz = a[2] + (b[2]-a[2])*t
                dx, dy, dz = px-cam[0], py-cam[1], pz-cam[2]
                depth = dx*fx + dy*fy + dz*fz
                if depth < 0.02 or depth > vn - 0.02:
                    continue          # πίσω από την κάμερα ή πέρα από τον στόχο
                # ΟΡΘΟΓΩΝΙΟ κάδρο, όχι κώνος: ο βραχίονας συνήθως μπαίνει
                # από το πλάι, εκεί που ένας κεντρικός κώνος δεν τον έβλεπε.
                hx = abs(dx*rx + dy*ry + dz*rz) - LINK_RADIUS
                hy = abs(dx*ux + dy*uy + dz*uz) - LINK_RADIUS
                # Πόσο έξω από το κάδρο είναι; Ο σύνδεσμος είναι ΜΕΣΑ μόνο
                # αν βρίσκεται εντός ΚΑΙ οριζόντια ΚΑΙ κάθετα, οπότε το
                # περιθώριό του είναι ο ΜΕΓΑΛΥΤΕΡΟΣ από τους δύο λόγους.
                ratio = max(hx/(depth*tx), hy/(depth*ty))
                if ratio < worst:
                    worst = ratio
        return worst

    def current_joints(self):
        """Οι ΤΩΡΙΝΕΣ θέσεις αρθρώσεων (σπόρος για το IK), ή None."""
        try:
            psm = self.ur5e.get_planning_scene_monitor()
            with psm.read_only() as scene:
                st = scene.current_state
                st.update()
                return [float(v) for v in
                        st.get_joint_group_positions(PLANNING_GROUP)]
        except Exception as e:
            if not self.seed_warned:
                self.seed_warned = True
                print(f"   [!] χωρίς τωρινή στάση για σπόρο IK ({type(e).__name__}:"
                      f" {e}) - IK από προεπιλογή", flush=True)
            return None

    def move_to(self, cam, look, label):
        """Μετακινεί την ΚΑΜΕΡΑ στη θέση `cam`, κοιτώντας το σημείο `look`.

        Βήματα (όλα ΠΡΙΝ ρωτηθεί ο planner - φθηνοί έλεγχοι πρώτα):
          1. εμβέλεια (MIN_REACH..MAX_REACH) και απόσταση από βαλίτσες (clearance)
          2. για κάθε περιστροφή γύρω από τον άξονα θέασης (ROLL_OPTIONS):
             IK με σπόρο την τωρινή στάση -> έλεγχος αυτο-απόκρυψης στη λύση ->
             κρατάμε τη λύση με τη ΜΙΚΡΟΤΕΡΗ κίνηση αρθρώσεων
          3. ο planner πηγαίνει ΑΚΡΙΒΩΣ σε εκείνη τη στάση αρθρώσεων
        Επιστρέφει True αν ο βραχίονας κινήθηκε. Κάθε απόρριψη μετράει σε έναν
        μετρητή rej_* που τυπώνεται στον επόμενο κύκλο (για διάγνωση).
        """
        d = reach(cam)
        if d > MAX_REACH or d < MIN_REACH:
            self.rej_reach += 1
            return False
        # Ποτέ σε θέση που ο έλεγχος ασφαλείας θα έκρινε «κίνδυνο σύγκρουσης»
        # (αλλιώς πήγαινε εκεί και στον επόμενο κύκλο έφευγε, χωρίς να δει τίποτα).
        for _b, (_p, _y) in self.boxes.items():
            if self.clearance(cam, BODY_IDS[_b]['dims'], _p, _y) < HARD_CLEARANCE + 0.01:
                self.rej_clear += 1
                return False
        goal = PoseStamped()
        goal.header.frame_id = BASE_FRAME
        goal.pose.position.x, goal.pose.position.y, goal.pose.position.z = map(float, cam)

        # --- ΕΛΕΥΘΕΡΟ ROLL + ΓΡΗΓΟΡΟΣ ΕΛΕΓΧΟΣ IK ---
        # Δοκιμάζουμε περιστροφές γύρω από τον άξονα θέασης. Η κάμερα βλέπει
        # ΤΟ ΙΔΙΟ πράγμα σε κάθε περίπτωση - αλλάζει μόνο ο προσανατολισμός της
        # εικόνας, που το ArUco αγνοεί. Για κάθε μία: IK με σπόρο την ΤΩΡΙΝΗ
        # στάση, έλεγχος αυτο-απόκρυψης, και κρατάμε τη λύση με τη ΜΙΚΡΟΤΕΡΗ
        # κίνηση αρθρώσεων (όχι σβούρα).
        seed = self.current_joints()
        best, any_ik = None, False       # best = (κίνηση, q, note, roll, rs)
        for roll in ROLL_OPTIONS:
            q = look_at_quaternion(cam, look, roll)
            goal.pose.orientation.x, goal.pose.orientation.y, \
                goal.pose.orientation.z, goal.pose.orientation.w = q
            note = ''
            try:
                rs = RobotState(self.ur5e.get_robot_model())
                rs.set_to_default_values()
                if seed is not None:
                    rs.set_joint_group_positions(PLANNING_GROUP, seed)
                    rs.update()
                if not rs.set_from_ik(PLANNING_GROUP, goal.pose,
                                      CAMERA_LINK, timeout=IK_TIMEOUT):
                    continue                      # αυτή η περιστροφή δεν φτάνει
                any_ik = True
                try:
                    rs.update()
                except Exception:
                    pass
                # --- ΑΥΤΟ-ΑΠΟΚΡΥΨΗ στην ΠΡΑΓΜΑΤΙΚΗ στάση της λύσης IK ---
                margin = self.self_occludes(rs, cam, look, quat_axes(q))
                if margin is None:                # FK μη διαθέσιμη -> ευρετική
                    if self_view_angle(cam, look) < SELF_VIEW_ANGLE:
                        continue
                else:
                    if margin < 1.0:
                        continue                  # ο βραχίονας στο κάδρο
                    note = (f"  [βραχίονας {margin:.2f}x του κάδρου]"
                            if margin < 9.0 else "  [κάδρο καθαρό]")
                mv = 0.0
                if seed is not None:
                    sol = rs.get_joint_group_positions(PLANNING_GROUP)
                    mv = max(abs(float(a) - b) for a, b in zip(sol, seed))
            except Exception as e:
                # ΔΕΝ το καταπίνουμε σιωπηλά: αν το set_from_ik σκάει σε
                # κάθε κλήση, ο pre-check είναι ανενεργός και κάθε αδύνατος
                # στόχος ξανακοστίζει 10s στον planner - χωρίς ίχνος στα logs.
                if not self.ik_warned:
                    self.ik_warned = True
                    print(f"   [!] IK pre-check ΑΝΕΝΕΡΓΟΣ ({type(e).__name__}:"
                          f" {e}) - ο planner θα αργεί σε αδύνατους στόχους",
                          flush=True)
                any_ik = True
                best = (0.0, q, '', roll, None)
                break
            if best is None or mv < best[0]:
                best = (mv, q, note, roll, rs)
            if mv < SMALL_MOVE:
                break                             # αρκετά μικρή κίνηση - κράτα τη

        if best is None:
            # Καμία περιστροφή δεν έδωσε αποδεκτή λύση.
            if any_ik:
                self.rej_occl += 1      # έφτανε, αλλά ο βραχίονας έμπαινε μπροστά
            else:
                self.rej_ik += 1        # δεν έφτανε με καμία περιστροφή
            return False

        mv, q, self.occl_note, roll, rs = best
        if abs(roll) > 1e-9:
            self.occl_note += f" [roll {math.degrees(roll):+.0f}°]"
        if seed is not None and rs is not None:
            self.occl_note += f" [αρθρώσεις έως {math.degrees(mv):.0f}°]"
        goal.pose.orientation.x, goal.pose.orientation.y, \
            goal.pose.orientation.z, goal.pose.orientation.w = q

        self.arm.set_start_state_to_current_state()
        goal_ok = False
        if rs is not None:
            # Στόχος = η ΙΔΙΑ στάση αρθρώσεων που ελέγξαμε (αυτο-απόκρυψη,
            # μικρή κίνηση). Όχι πόζα, που ο planner θα έλυνε ξανά μόνος του.
            try:
                self.arm.set_goal_state(robot_state=rs)
                goal_ok = True
            except Exception as e:
                if not self.goal_warned:
                    self.goal_warned = True
                    print(f"   [!] στόχος-στάση μη διαθέσιμος ({type(e).__name__}:"
                          f" {e}) - στόχος-πόζα", flush=True)
        if not goal_ok:
            self.arm.set_goal_state(pose_stamped_msg=goal,
                                    pose_link=CAMERA_LINK)
        plan = self.arm.plan()
        if not plan:
            self.rej_plan += 1        # IK και κάδρο εντάξει, ο planner απέτυχε
            return False
        print(f"   -> {label}: κάμερα({cam[0]:.2f},{cam[1]:.2f},{cam[2]:.2f}) "
              f"d={d:.2f}m{self.occl_note}", flush=True)
        self.ur5e.execute(plan.trajectory, controllers=[])
        self.in_watch = False
        self.stuck = 0
        time.sleep(SETTLE)
        return True

    def nudge_to_front(self, pos, n_az, cam):
        """ΜΙΚΡΗ διόρθωση προς μετωπικά γύρω από το tag, ΑΠΟ ΤΗΝ ΤΩΡΙΝΗ θέση.

        Δεν υπολογίζει νέα θέση από την αρχή: κρατά (περίπου) την ίδια απόσταση
        και στρέφεται γύρω από το tag προς την κάθετό του - πλήρως, αλλιώς τα
        2/3, αλλιώς το 1/3 του δρόμου. Το tag μένει στο κέντρο του κάδρου.
        """
        if n_az is None or cam is None:
            return False
        vx, vy, vz = cam[0]-pos[0], cam[1]-pos[1], cam[2]-pos[2]
        d = math.sqrt(vx*vx + vy*vy + vz*vz)
        if d < 1e-3:
            return False
        az = (math.atan2(vy, vx) - n_az + math.pi) % (2*math.pi) - math.pi
        el = math.atan2(vz, math.hypot(vx, vy))
        obl0 = math.degrees(math.acos(max(-1.0, min(1.0, math.cos(az)*math.cos(el)))))
        dn = min(max(d, HANDLE_GOOD_MIN + 0.03), HANDLE_GOOD_MAX - 0.03)
        e_min = min(el, math.radians(8))
        for f in (0.0, 1/3, 2/3):
            a, e = az*f, max(e_min, el*f)
            o = math.degrees(math.acos(max(-1.0, min(1.0, math.cos(a)*math.cos(e)))))
            c = (pos[0] + dn*math.cos(e)*math.cos(n_az + a),
                 pos[1] + dn*math.cos(e)*math.sin(n_az + a),
                 pos[2] + dn*math.sin(e))
            if self.move_to(c, pos, f"μικρή διόρθωση προς μετωπικά "
                                    f"[λοξότητα {obl0:.0f}° -> {o:.0f}°, {dn:.2f}m]"):
                return True
        return False

    # ---------- επιτήρηση ----------
    def watch(self, reason=''):
        """Πηγαίνει σε θέση επιτήρησης (ΜΠΡΟΣΤΑ ή ΠΛΑΓΙΑ ΔΕΞΙΑ, κατά watch_mode)."""
        poses = WATCH_FORWARD if self.watch_mode == 'forward' else WATCH_RIGHT
        name = 'ΜΠΡΟΣΤΑ' if self.watch_mode == 'forward' else 'ΠΛΑΓΙΑ ΔΕΞΙΑ'
        if self.in_watch:
            print(f"   (ήδη σε επιτήρηση {name}) {reason}", flush=True)
            return True
        print(f"   >>> ΕΠΙΤΗΡΗΣΗ {name} {reason}", flush=True)
        for cam, look in poses:
            if self.move_to(cam, look, f"επιτήρηση {name}"):
                self.in_watch = True
                return True
        print("   [!] καμία θέση επιτήρησης δεν σχεδιάστηκε", flush=True)
        return False

    def toggle_watch(self):
        """Αλλάζει κατεύθυνση επιτήρησης (ΜΠΡΟΣΤΑ <-> ΠΛΑΓΙΑ ΔΕΞΙΑ)."""
        self.watch_mode = 'right' if self.watch_mode == 'forward' else 'forward'
        self.in_watch = False
        self.blind_cycles = 0
        print(f"   ~~~ αλλαγή κατεύθυνσης επιτήρησης -> "
              f"{'ΠΛΑΓΙΑ ΔΕΞΙΑ' if self.watch_mode=='right' else 'ΜΠΡΟΣΤΑ'}",
              flush=True)

    # ---------- ευρύ πλάνο ----------
    def elevate_view(self, pos, label):
        """Ανεβαίνει ψηλότερα και πίσω για ευρύτερο πλάνο του σημείου."""
        n = reach(pos)
        if n < 1e-6:
            return False
        ux, uy = pos[0]/n, pos[1]/n
        for back, height in ELEVATE_VIEWS:
            cam = (pos[0]-ux*back, pos[1]-uy*back, pos[2]+height)
            if self.move_to(cam, pos, label):
                return True
        print(f"   [skip] {label}: εκτός εμβέλειας", flush=True)
        return False

    def approach_wheel_end(self, bid, bpos, m):
        """Μετά το ευρύ πλάνο φαίνεται ΕΝΑ ροδάκι: ΛΙΓΟ πιο κοντά ώστε να μπει
        στο κάδρο και το δεύτερο.

        ΔΕΝ πηγαίνει πάνω στο ροδάκι (το παλιό 0.30m έβλεπε μόνο ΕΝΑ). Κοιτάζει
        το ΚΕΝΤΡΟ της άκρης με τα ροδάκια - εκτίμηση από το ένα ροδάκι και τον
        άξονα της βαλίτσας - από APPROACH_FRAC της τωρινής απόστασης, ποτέ
        κάτω από APPROACH_MIN.
        """
        loc1, wpos = m.one_wheel
        # Τα ροδάκια είναι σε ΣΤΕΝΗ άκρη = τοπικά ±90°. Ποια από τις δύο;
        # Αυτή που είναι πιο κοντά στο ροδάκι που είδαμε.
        a = m.absol(math.pi/2 if math.sin(loc1) >= 0 else -math.pi/2)
        half = self.half_extent(bid, a)
        T = (bpos[0] + math.cos(a)*half, bpos[1] + math.sin(a)*half, wpos[2])
        cam = self.listener.camera_position()
        if cam is None:
            return False
        d = math.dist(cam, T)
        if d <= APPROACH_MIN + 0.02:
            print(f"   ήδη κοντά στην άκρη των ροδακιών ({d:.2f}m) - "
                  f"δεν πλησιάζω άλλο", flush=True)
            return False
        dn = max(APPROACH_MIN, APPROACH_FRAC*d)
        az0 = math.atan2(cam[1]-T[1], cam[0]-T[0])
        el0 = math.asin(max(-1.0, min(1.0, (cam[2]-T[2])/d)))
        for daz in (0.0, 20.0, -20.0):
            for dele in (0.0, 10.0, -10.0):
                az = az0 + math.radians(daz)
                el = max(math.radians(5.0), el0 + math.radians(dele))
                c = (T[0] + dn*math.cos(el)*math.cos(az),
                     T[1] + dn*math.cos(el)*math.sin(az),
                     T[2] + dn*math.sin(el))
                if self.move_to(c, T, f"λίγο πιο κοντά στην άκρη των ροδακιών "
                                      f"[{d:.2f} -> {dn:.2f}m]"):
                    return True
        print("   [skip] πλησίασμα άκρης ροδακιών: καμία εφικτή θέση", flush=True)
        return False

    def known_pos(self, bid, det, now):
        """Θέση βαλίτσας: ορατή ΤΩΡΑ, αλλιώς από τη ΜΝΗΜΗ αν δεν είναι
        παλιότερη από SEARCH_MEMORY. None αν δεν την ξέρουμε."""
        if bid in det:
            return det[bid]
        m = self.mem.get(bid)
        if m is not None and m.pos is not None and now - m.t < SEARCH_MEMORY:
            return m.pos
        return None

    def closing_body(self, det):
        """Ποια βαλίτσα κινείται ΠΡΟΣ την κάμερα (και πόσο γρήγορα).
        Επιστρέφει (bid, ταχύτητα προσέγγισης) ή None."""
        cam = self.listener.camera_position()
        if cam is None:
            return None
        worst = None
        for bid, pos in det.items():
            if bid not in BODY_IDS:
                continue
            vx, vy = self.velocity(bid)
            if math.hypot(vx, vy) < MOVING_SPEED:
                continue
            dx, dy = cam[0]-pos[0], cam[1]-pos[1]
            n = math.hypot(dx, dy)
            if n < 1e-6:
                continue
            # προβολή ταχύτητας πάνω στη γραμμή βαλίτσα->κάμερα
            closing = (vx*dx + vy*dy) / n
            if closing > MOVING_SPEED and (worst is None or closing > worst[1]):
                worst = (bid, closing)
        return worst

    def retreat_keeping_view(self, pos, label):
        """Τραβιέται πίσω/πάνω ΧΩΡΙΣ να χάσει τον στόχο από το κάδρο."""
        n = reach(pos)
        if n < 1e-6:
            return False
        u = (pos[0]/n, pos[1]/n, pos[2]/n)
        for back, up in ((RETREAT_BACK, RETREAT_UP),
                         (RETREAT_BACK*1.5, RETREAT_UP*1.4),
                         (RETREAT_BACK*0.7, RETREAT_UP*1.8)):
            so = HANDLE_SAFE_DIST + back
            cam = (pos[0]-u[0]*so, pos[1]-u[1]*so, pos[2]+up)
            if self.move_to(cam, pos, f"{label} [πίσω {back:.2f} πάνω {up:.2f}]"):
                return True
        print(f"   [skip] {label}: εκτός εμβέλειας", flush=True)
        return False

    # ---------- θέαση υπό γωνία ----------
    def half_extent(self, bid, ang):
        """Απόσταση από το κέντρο της βαλίτσας ως την πλευρά της προς την απόλυτη γωνία ang."""
        L, W, _ = BODY_IDS.get(bid, {'dims': DEFAULT_DIMS})['dims']
        d = ang - self.yaws.get(bid, 0.0)
        return abs(L/2*math.cos(d)) + abs(W/2*math.sin(d))

    def memory(self, bid):
        """Η μνήμη μιας βαλίτσας - δημιουργείται με το που τη δούμε."""
        if bid not in self.mem:
            self.mem[bid] = SuitcaseMemory(bid)
        return self.mem[bid]

    def wheel_angle(self, bid):
        """Απόλυτη γωνία προς τα ροδάκια - ή None αν άγνωστη.

        Αποθηκεύεται ΣΧΕΤΙΚΑ με τον άξονα της βαλίτσας. Η βαλίτσα γυρίζει
        καθώς προχωράει στην ταινία: μια ΑΠΟΛΥΤΗ γωνία παύει να ισχύει μέσα
        σε δευτερόλεπτα και τότε ο κανόνας απαγορεύει τη ΣΩΣΤΗ πλευρά.
        """
        m = self.mem.get(bid)
        if m is None or m.wheel_loc is None:
            return None
        return m.absol(m.wheel_loc)       # ΔΕΝ λήγει: είναι τοπική γωνία

    def view_angle(self, bid, bpos, ang, label):
        """Πάει να δει την ΠΛΕΥΡΑ της βαλίτσας που κοιτάζει προς την απόλυτη γωνία ang.

        Υποψήφιες θέσεις: FACE_OFFSETS (πλάγια) x FACE_VIEWS (απόσταση, ύψος),
        με σειρά από την πιο ΜΕΤΩΠΙΚΗ (ανά 10° λοξότητας) και μέσα σε αυτές την
        πιο κοντινή στη βάση. Ποτέ προς τη μεριά των ροδακιών. Αν πετύχει, η
        πλευρά σημειώνεται ως επισκεφθείσα στη μνήμη. True αν κινήθηκε.
        """
        # --- ΚΑΘΟΛΙΚΟΣ ΚΑΝΟΝΑΣ: ποτέ προς τη μεριά των ροδακιών ---
        wd = self.wheel_angle(bid)
        if wd is not None and ang_diff(ang, wd) < WHEEL_EXCLUDE:
            print(f"    [ΑΓΝΟΩ] {label}: είναι η μεριά ΤΩΝ ΡΟΔΑΚΙΩΝ "
                  f"- εκεί δεν υπάρχει χερούλι", flush=True)
            return False
        half = self.half_extent(bid, ang)
        nx, ny = math.cos(ang), math.sin(ang)
        face_pt = (bpos[0]+nx*half, bpos[1]+ny*half, bpos[2])
        br = reach(bpos)
        cands = []
        for off in FACE_OFFSETS:
            a2 = ang + off
            mx, my = math.cos(a2), math.sin(a2)
            for dist, elev in FACE_VIEWS:
                e = math.radians(elev)
                cam = (face_pt[0]+mx*dist*math.cos(e),
                       face_pt[1]+my*dist*math.cos(e),
                       face_pt[2]+dist*math.sin(e))
                r = reach(cam)
                if r > MAX_REACH or r < MIN_REACH:
                    continue
                far = 0 if r <= br + 0.03 else 1
                # ΛΟΞΟΤΗΤΑ: γωνία ανάμεσα στην κάθετο της όψης και στη
                # διεύθυνση όψη->κάμερα (πλάγια μετατόπιση ΚΑΙ ύψος μαζί).
                obl = math.degrees(math.acos(max(-1.0, min(1.0,
                                                 math.cos(off)*math.cos(e)))))
                cands.append((far, abs(off), r, cam, obl))
        if not cands:
            print(f"   [skip] {label}: εκτός εμβέλειας", flush=True)
            return False
        # FACE TO FACE: ΠΡΩΤΑ οι πιο ΜΕΤΩΠΙΚΕΣ θέσεις (ανά 10° λοξότητας) και
        # μόνο μέσα σε αυτές η πιο κοντινή. Παλιά η σειρά ήταν «πιο κοντά στη
        # βάση πρώτα» -> έβγαινε σχεδόν πάντα η πιο ΛΟΞΗ (65°), όπου το tag
        # φαίνεται ξυστά και το ArUco δεν το διαβάζει.
        cands.sort(key=lambda c: (int(c[4] // 10), c[2]))
        for far, off, r, cam, obl in cands:
            tag = (f" [λοξότητα {obl:.0f}°]" if obl >= 1.0 else " [ΜΕΤΩΠΙΚΑ]")
            if self.move_to(cam, face_pt,
                            f"{label}{tag}{' [ΠΕΡΑ]' if far else ''}"):
                self.memory(bid).mark(ang, label, time.time())
                return True
        print(f"   [fail] {label}: κανένας από {len(cands)} υποψήφιους "
              f"(στον κύκλο ως τώρα: αυτο-απόκρυψη {self.rej_occl}, χωρίς IK "
              f"{self.rej_ik}, planner {self.rej_plan})", flush=True)
        return False

    def face_normal(self, bid, a):
        """Η ΚΑΘΕΤΟΣ της όψης της βαλίτσας που είναι πιο κοντά στη γωνία a.
        Οι 4 όψεις κοιτάζουν στις yaw + k*90°. Face to face = κάμερα πάνω της.
        """
        yaw = self.yaws.get(bid, 0.0)
        return yaw + round((a - yaw) / (math.pi/2)) * (math.pi/2)

    def side_plan(self, bid, bpos):
        """Σειρά πλευρών όταν ξέρουμε πού είναι τα ροδάκια:
          1) ΑΠΕΝΑΝΤΙ από τα ροδάκια (στενή άκρη)
          2) η ΠΙΟ ΚΟΝΤΙΝΗ / ευκολότερη μακριά πλευρά
          3) η άλλη μακριά πλευρά (ακόμα κι αν θέλει πλήρες τέντωμα)
        Η μεριά των ροδακιών δεν μπαίνει ποτέ. None αν τα ροδάκια είναι άγνωστα.
        «Κοντινή» = το κέντρο της όψης είναι πιο κοντά στη βάση του βραχίονα.
        """
        wdir = self.wheel_angle(bid)
        if wdir is None:
            return None

        def face_reach(a):
            """Απόσταση από τη βάση του κέντρου της πλευράς προς την a (πόσο «εύκολη» είναι)."""
            h = self.half_extent(bid, a)
            return reach((bpos[0] + math.cos(a)*h, bpos[1] + math.sin(a)*h, bpos[2]))
        near, far = sorted((wdir + math.pi/2, wdir - math.pi/2), key=face_reach)
        return [("ΑΠΕΝΑΝΤΙ ΑΠΟ ΡΟΔΑΚΙΑ (στενή άκρη)", wdir + math.pi),
                (f"ΜΑΚΡΙΑ πλευρά ΚΟΝΤΙΝΗ ({face_reach(near):.2f}m)", near),
                (f"ΜΑΚΡΙΑ πλευρά ΜΑΚΡΙΝΗ ({face_reach(far):.2f}m)", far)]

    def current_angle(self, bpos):
        """Από ποια γωνία (γύρω από τη βαλίτσα) κοιτάζει τώρα η κάμερα, ή None."""
        cam = self.listener.camera_position()
        if cam is None:
            return None
        return math.atan2(cam[1]-bpos[1], cam[0]-bpos[0])

    def refine_current(self, bid, bpos):
        """Μικρές διορθώσεις ΣΤΗΝ ΙΔΙΑ πλευρά πριν πάμε στην επόμενη (βήμα 2γ).

        Τρέχει μόνο αν η κάμερα στέκεται σε πλευρά που ΕΠΙΛΕΞΑΜΕ (όχι στη μεριά
        των ροδακιών, όχι στην πλευρά του απλού). Μία διόρθωση ανά κύκλο, το
        πολύ REFINE_MAX, ΑΠΟ ΤΗΝ ΤΩΡΙΝΗ ΘΕΣΗ (small_correction):
          θέα ΜΕΤΩΠΙΚΗ, τίποτα δεν φάνηκε -> ΚΑΜΙΑ διόρθωση (χωρίς χαμένο χρόνο)
          θέα ΛΟΞΗ                          -> μόνο «πιο μετωπικά»
          (με 'hint' στην πλευρά επιτρέπονται και ματιές δεξιά/αριστερά -
           σήμερα το 'hint' δεν τίθεται πουθενά, γιατί ο προορισμός σε 1 καρέ
           μετράει ήδη ως «βρέθηκε»)
        False = τίποτα άλλο εδώ, συνέχισε στην επόμενη πλευρά.
        """
        cur = self.current_angle(bpos)
        if cur is None:
            return False

        # ΠΟΤΕ δεν επιμένουμε στη μεριά των ροδακιών - εκεί δεν υπάρχει
        # χερούλι, όσο κι αν διορθώσουμε τη θέαση.
        wd = self.wheel_angle(bid)
        if wd is not None and ang_diff(cur, wd) < WHEEL_EXCLUDE:
            return False

        # Μόνο σε πλευρά που ΕΠΙΛΕΞΑΜΕ. Αν ο βραχίονας στέκεται σε θέση
        # επιτήρησης ή κάπου τυχαία, δεν έχει νόημα να «διορθώσουμε» εκεί.
        m = self.memory(bid)
        sd = m.find(cur)
        if sd is None or not sd['visited'] or sd['plain']:
            return False          # δεν είμαστε σε πλευρά που επιλέξαμε

        if sd['refine'] >= REFINE_MAX:
            print(f"   οι διορθώσεις σε αυτή την πλευρά εξαντλήθηκαν "
                  f"({REFINE_MAX}/{REFINE_MAX}) -> αλλάζω πλευρά", flush=True)
            return False
        F = self.face_normal(bid, cur)
        half = self.half_extent(bid, F)
        face = (bpos[0] + math.cos(F)*half, bpos[1] + math.sin(F)*half, bpos[2])
        hint = bool(sd.get('hint'))
        if not hint:
            # Καμία ανίχνευση εδώ. Σε ΚΑΛΗ (μετωπική) θέση δεν χάνουμε χρόνο:
            # επόμενη πλευρά. Μόνο αν η θέα είναι ΛΟΞΗ, προσπαθούμε να πάμε
            # πιο μετωπικά (όχι ματιές δεξιά/αριστερά).
            o = self.view_obliquity(face, F)
            if o is None or o <= REFINE_FRONT_TOL:
                if not sd.get('nohint_said'):
                    sd['nohint_said'] = True
                    print("   θέα μετωπική, καμία ανίχνευση -> χωρίς διορθώσεις, "
                          "επόμενη πλευρά", flush=True)
                return False
        if self.small_correction(face, F, sd, REFINE_MAX, "διόρθωση",
                                 allow_peeks=hint):
            return True
        print("   καμία άλλη μικρή διόρθωση εδώ -> αλλάζω πλευρά", flush=True)
        return False

    def view_obliquity(self, center, normal):
        """Πόσο λοξά (rad) βλέπει ΤΩΡΑ η κάμερα το center ως προς την κάθετο."""
        cam = self.listener.camera_position()
        if cam is None:
            return None
        vx, vy, vz = cam[0]-center[0], cam[1]-center[1], cam[2]-center[2]
        if math.sqrt(vx*vx + vy*vy + vz*vz) < 1e-3:
            return None
        az = (math.atan2(vy, vx) - normal + math.pi) % (2*math.pi) - math.pi
        el = math.atan2(vz, math.hypot(vx, vy))
        return math.acos(max(-1.0, min(1.0, math.cos(az)*math.cos(el))))

    def small_correction(self, center, normal, st, n_max, what, allow_peeks=True):
        """ΜΙΑ μικρή διόρθωση γύρω από το center, ΑΠΟ ΤΗΝ ΤΩΡΙΝΗ ΘΕΣΗ.

        Ίδια απόσταση, απλώς στροφή γύρω από το ίδιο σημείο:
          ΛΟΞΑ         -> όσο πιο μετωπικά γίνεται (πλήρως, 2/3, 1/3)
          ήδη ΜΕΤΩΠΙΚΑ -> λίγο από ΔΕΞΙΑ, λίγο από ΑΡΙΣΤΕΡΑ, ίσια πιο κοντά
        st: {'refine': πόσες έγιναν, 'peek': ποια ματιά ακολουθεί}.
        allow_peeks=False: μόνο «πιο μετωπικά» (όταν δεν έχει φανεί τίποτα).
        normal: αζιμούθιο της καθέτου (None -> η τωρινή διεύθυνση = μετωπική).
        """
        cam = self.listener.camera_position()
        if cam is None:
            return False
        vx, vy, vz = cam[0]-center[0], cam[1]-center[1], cam[2]-center[2]
        d = math.sqrt(vx*vx + vy*vy + vz*vz)
        if d < 1e-3:
            return False
        F = normal if normal is not None else math.atan2(vy, vx)
        az = (math.atan2(vy, vx) - F + math.pi) % (2*math.pi) - math.pi
        el = math.atan2(vz, math.hypot(vx, vy))
        obl = math.acos(max(-1.0, min(1.0, math.cos(az)*math.cos(el))))

        def pose(a, e, dist):
            """Θέση κάμερας σε απόκλιση a, ύψος e και απόσταση dist από το center."""
            return (center[0] + math.cos(F+a)*dist*math.cos(e),
                    center[1] + math.sin(F+a)*dist*math.cos(e),
                    center[2] + dist*math.sin(e))

        n = st['refine'] + 1
        if obl <= REFINE_FRONT_TOL and not allow_peeks:
            st['refine'] = n_max      # ήδη μετωπικά και χωρίς ανίχνευση: τέλος
            return False
        if obl <= REFINE_FRONT_TOL:
            # ΗΔΗ ΜΕΤΩΠΙΚΑ -> μικρή ματιά δεξιά, αριστερά, ίσια πιο κοντά
            peeks = [(+REFINE_PEEK, el, d, "λίγο από ΔΕΞΙΑ"),
                     (-REFINE_PEEK, el, d, "λίγο από ΑΡΙΣΤΕΡΑ"),
                     (0.0, el*0.5, max(REFINE_MIN_DIST, d - REFINE_CLOSER),
                      "ίσια, λίγο πιο κοντά")]
            while st['peek'] < len(peeks):
                a, e, dist, txt = peeks[st['peek']]
                st['peek'] += 1
                if self.move_to(pose(a, e, dist), center,
                                f"{what} {n}/{n_max}: {txt} "
                                f"[{math.degrees(a):+.0f}°, {dist:.2f}m]"):
                    st['refine'] = n
                    return True
        else:
            # ΛΟΞΑ -> όσο πιο μετωπικά γίνεται, από την ίδια απόσταση
            e_min = min(el, math.radians(8))
            for f in (0.0, 1/3, 2/3):
                a, e = az*f, max(e_min, el*f)
                o = math.degrees(math.acos(max(-1.0, min(1.0,
                                                         math.cos(a)*math.cos(e)))))
                if self.move_to(pose(a, e, d), center,
                                f"{what} {n}/{n_max}: πιο μετωπικά "
                                f"[λοξότητα {math.degrees(obl):.0f}° -> {o:.0f}°]"):
                    st['refine'] = n
                    return True
        # καμία μικρή κίνηση δεν φτάνεται -> τέλος διορθώσεων εδώ
        st['refine'] = n_max
        return False

    def step_around(self, bid, bpos):
        """Γύρος στις ΟΨΕΙΣ της βαλίτσας (βήμα 2δ) - όταν τα ροδάκια είναι άγνωστα.

        Βήματα ANGLE_STEPS από τη γωνία όπου στεκόμαστε, στρογγυλεμένα στην
        ΚΑΘΕΤΟ της κοντινότερης όψης (face to face). Παραλείπει ελεγμένες όψεις
        και τη μεριά των ροδακιών (αν έγινε γνωστή). Όταν ελεγχθούν όλες ->
        τέλος γύρου (finish_search). True = κάτι έγινε σε αυτόν τον κύκλο.
        """
        cur = self.current_angle(bpos)
        if cur is None:
            cur = math.atan2(bpos[1], bpos[0]) + math.pi
        m = self.memory(bid)
        seen = []
        for deg in ANGLE_STEPS:
            # FACE TO FACE: το βήμα στρογγυλεύεται στην ΚΑΘΕΤΟ της πιο κοντινής
            # όψης - αλλιώς η κάμερα κοίταζε την πλευρά υπό τυχαία γωνία.
            ang = self.face_normal(bid, cur + math.radians(deg))
            if any(ang_diff(ang, s) < 0.01 for s in seen):
                continue
            seen.append(ang)
            wd = self.wheel_angle(bid)
            if wd is not None and ang_diff(ang, wd) < WHEEL_EXCLUDE:
                continue                  # ποτέ η μεριά των ροδακιών
            if m.done_side(ang):
                continue
            if self.view_angle(bid, bpos, ang, f"στροφή {deg:+d}° -> όψη"):
                return True
            self.note_fail(bid, ang, f"στροφή {deg:+d}° -> όψη")
        # Όλες οι όψεις (εκτός από των ροδακιών) ελεγμένες -> ΤΕΛΟΣ, όχι
        # μηδενισμός και από την αρχή.
        yaw = self.yaws.get(bid, 0.0)
        faces = [yaw + k*math.pi/2 for k in range(4)]
        wd = self.wheel_angle(bid)
        faces = [f for f in faces if wd is None or ang_diff(f, wd) >= WHEEL_EXCLUDE]
        if all(m.done_side(f) for f in faces):
            self.finish_search(bid, time.time())
            return True
        return False

    def handle_face(self, bid, bpos, hpos):
        """Σε ΠΟΙΑ ΠΛΕΥΡΑ της βαλίτσας βρίσκεται ένα χερούλι; (εφεδρικό)
        Υπολογίζουμε τη γωνία του ΩΣ ΠΡΟΣ ΤΟΝ ΑΞΟΝΑ της βαλίτσας (yaw).
        Επιστρέφει (ετικέτα, τοπική γωνία, απόλυτη γωνία).

        Γεωμετρία (επαληθευμένη): η κατεύθυνση yaw (τοπικό ±X) δείχνει στις
        ΜΑΚΡΙΕΣ πλευρές, το yaw±90° (τοπικό ±Y) στις ΣΤΕΝΕΣ άκρες.
        """
        yaw = self.yaws.get(bid, 0.0)
        abs_ang = math.atan2(hpos[1]-bpos[1], hpos[0]-bpos[0])
        loc = (abs_ang - yaw + math.pi) % (2*math.pi) - math.pi   # -π..π
        d = abs(loc)
        if d < math.radians(45):
            lbl = 'μακριά +X'
        elif d > math.radians(135):
            lbl = 'μακριά -X'
        elif loc > 0:
            lbl = 'στενή +Y'
        else:
            lbl = 'στενή -Y'
        return lbl, loc, abs_ang

    def search_dest_angles(self, bid, bpos, plain_pos, n_wheels, wheels):
        """Πού να ψάξουμε το tag ΠΡΟΟΡΙΣΜΟΥ, δεδομένου πού είναι το ΑΠΛΟ; (εφεδρικό)

        Χρησιμοποιείται ΜΟΝΟ όταν η κατεύθυνση των ροδακιών είναι άγνωστη -
        αλλιώς η σειρά πλευρών έρχεται από το side_plan. Τα δύο χερούλια
        είναι ΠΑΝΤΑ σε διαφορετικές πλευρές, άρα η πλευρά του απλού
        αποκλείεται:

          ΑΠΛΟ σε ΜΑΚΡΙΑ πλευρά (η συνηθισμένη περίπτωση εδώ)
            -> δοκιμάζουμε τις δύο ΣΤΕΝΕΣ άκρες και μετά την ΑΠΕΝΑΝΤΙ μακριά
               (τα ροδάκια είναι άγνωστα, άρα δεν ξέρουμε ποια στενή είναι
               η δική τους).

          ΑΠΛΟ σε ΣΤΕΝΗ άκρη (σπάνιο εδώ: τότε τα ροδάκια συμπεραίνονται
          αμέσως και αναλαμβάνει το side_plan)
            -> δοκιμάζουμε τις ΜΑΚΡΙΕΣ πλευρές. Αν φαίνονται ροδάκια, πρώτα
               εκείνη που είναι πιο κοντά στην κατεύθυνση «απέναντι από τα
               ροδάκια», με ±40° γύρω της.

        Επιστρέφει λίστα (ετικέτα, απόλυτη γωνία) με σειρά προτεραιότητας.
        """
        lbl, loc, abs_ang = self.handle_face(bid, bpos, plain_pos)
        yaw = self.yaws.get(bid, 0.0)
        on_long = lbl.startswith('μακριά')

        print(f"      Το απλό χερούλι είναι σε: {lbl}", flush=True)

        # Κατεύθυνση ΑΠΕΝΑΝΤΙ από τα ροδάκια (αν φαίνονται)
        opp_wheels = None
        if n_wheels:
            wx = sum(p[0] for p in wheels)/len(wheels)
            wy = sum(p[1] for p in wheels)/len(wheels)
            opp_wheels = math.atan2(bpos[1]-wy, bpos[0]-wx)

        out = []
        if not on_long:
            # ΑΠΛΟ σε ΣΤΕΝΗ άκρη -> στόχος σε ΜΑΚΡΙΑ πλευρά (τοπικό ±X)
            if opp_wheels is not None:
                lx_plus, lx_minus = yaw, yaw + math.pi
                if ang_diff(opp_wheels, lx_plus) < ang_diff(opp_wheels, lx_minus):
                    first = ('μακριά +X', lx_plus)
                else:
                    first = ('μακριά -X', lx_minus)
                print(f"      -> ροδάκια ορατά: πρώτα η {first[0]} "
                      f"(πιο κοντά στο απέναντι από τα ροδάκια)", flush=True)
                out = [(first[0], first[1]),
                       (f"{first[0]} +40°", first[1] + math.radians(40)),
                       (f"{first[0]} -40°", first[1] - math.radians(40))]
            else:
                print("      -> χωρίς ροδάκια: δοκιμάζω και τις δύο ΜΑΚΡΙΕΣ πλευρές",
                      flush=True)
                out = [('μακριά +X', yaw), ('μακριά -X', yaw + math.pi)]
        else:
            # ΑΠΛΟ σε ΜΑΚΡΙΑ πλευρά -> ΣΤΕΝΕΣ άκρες (τοπικό ±Y), μετά η απέναντι μακριά
            print("      -> πάω στις ΣΤΕΝΕΣ άκρες και μετά στην απέναντι μακριά",
                  flush=True)
            out = [('στενή +Y', yaw + math.pi/2),
                   ('στενή -Y', yaw - math.pi/2),
                   ('απέναντι μακριά', abs_ang + math.pi)]

        return out

    # ---------- χερούλι ----------
    def view_handle(self, pos, tag_yaw=None):
        """Τοποθετεί την κάμερα ΜΠΡΟΣΤΑ ΑΠΟ ΤΟ TAG (ΝΕΑ θέση, όχι μικρή διόρθωση).

        Αν ξέρουμε την κάθετο του tag, στεκόμαστε πάνω της (ανοχή ±VIEW_PERP_TOL)
        σε απόσταση HANDLE_STANDOFFS· μετωπικές θέσεις πρώτα, λοξές μετά.
        Χρησιμοποιείται για: επιστροφή σε προορισμό που φάνηκε στο πέρασμα (1β)
        και όταν αποτύχει η υποχώρηση από βαλίτσα που πλησιάζει. Οι διορθώσεις
        ΜΕΣΑ στην παραμονή γίνονται με nudge_to_front / small_correction.
        """
        n = reach(pos)
        if n < 1e-6:
            return False

        if tag_yaw is not None:
            # base_ang = ΠΡΟΣ ΤΑ ΠΟΥ ΚΟΙΤΑΖΕΙ το tag. ΕΚΕΙ πρέπει να σταθεί
            # η κάμερα: από την πίσω πλευρά το tag δεν φαίνεται καθόλου,
            # και στην ακμή του το ArUco δεν το διαβάζει.
            base_ang = tag_yaw
            src = "κάθετα στο tag"
            print(f"      [γεωμετρία] κάθετος tag {math.degrees(tag_yaw):.0f}° "
                  f"-> κάμερα εκεί, ανοχή ±{math.degrees(VIEW_PERP_TOL):.0f}°",
                  flush=True)
        else:
            # Χωρίς γνωστή κάθετο: κάμερα ανάμεσα σε βάση και χερούλι.
            base_ang = math.atan2(-pos[1], -pos[0])
            src = "γραμμή βάσης"
            print(f"      [γεωμετρία] ΧΩΡΙΣ κάθετο tag - γραμμή βάσης->χερούλι "
                  f"({math.degrees(base_ang):.0f}°). Η θέαση ΔΕΝ θα είναι "
                  f"απαραίτητα μετωπική!", flush=True)

        # ΣΕΙΡΑ ΠΡΟΤΕΡΑΙΟΤΗΤΑΣ: η ΓΩΝΙΑ μετράει περισσότερο από την απόσταση.
        # Δοκιμάζουμε ΟΛΕΣ τις αποστάσεις/ύψη μετωπικά ΠΡΩΤΑ, και μόνο αν
        # καμία δεν είναι εφικτή προχωράμε σε λοξή θέαση. Έτσι το tag
        # διαβάζεται όσο πιο κάθετα γίνεται κάθε φορά.
        for off in HANDLE_VIEW_OFFSETS:
            a = base_ang + off
            for so in HANDLE_STANDOFFS:
                # Το ΥΨΟΣ μετράει εξίσου στη λοξότητα: dz/so = εφαπτομένη
                # της γωνίας ανύψωσης. Το κρατάμε μέσα στην ίδια ανοχή.
                dzs = (0.0, so*math.tan(VIEW_PERP_TOL*0.6),
                       -so*math.tan(VIEW_PERP_TOL*0.6))
                for dz in dzs:
                    cam = (pos[0] + math.cos(a)*so,
                           pos[1] + math.sin(a)*so,
                           pos[2] + dz)
                    tag = (f" [{math.degrees(off):+.0f}°]" if abs(off) > 0.01
                           else " [ΜΕΤΩΠΙΚΑ]")
                    if self.move_to(cam, pos,
                                    f"θέαση χερουλιού {so:.2f}m{tag} ({src})"):
                        return True
        return False

    def handle_normal(self, hid):
        """Αζιμούθιο της καθέτου ενός tag, ή None αν δεν το ξέρουμε."""
        return tag_normal_az(self.quats.get(hid))

    def view_offset(self, cam, pos, hid):
        """Πόσο ΛΟΞΑ βλέπει ΤΩΡΑ η κάμερα το tag (rad), ή None αν άγνωστο.

        Η διεύθυνση tag->κάμερα πρέπει να συμπίπτει με την κάθετο του tag.
        """
        nz = self.handle_normal(hid)
        if nz is None:
            return None
        return ang_diff(math.atan2(cam[1]-pos[1], cam[0]-pos[0]), nz)

    def reset_handle(self):
        """Ξεχνά το tag προορισμού που παρακολουθούσαμε (και τις μικρές διορθώσεις του)."""
        self.handle_pos, self.handle_first_t, self.relook = None, 0.0, 0
        self.relook_st = {'refine': 0, 'peek': 0}
        self.dest_cycles, self.dest_fixed = 0, False

    # ---------- πλευρές: αποτυχίες / κίνδυνος / τέλος αναζήτησης ----------
    def note_fail(self, bid, a, label):
        """Καταγράφει ότι η πλευρά δεν φτάστηκε· μετά από SIDE_MAX_FAILS την
        παραλείπουμε (όχι ξανά και ξανά σε κάθε κύκλο)."""
        n = self.memory(bid).fail(a, label, time.time())
        if n >= SIDE_MAX_FAILS:
            print(f"   {label}: {n} αποτυχίες -> ΑΝΕΦΙΚΤΗ, δεν την ξαναδοκιμάζω",
                  flush=True)

    def retry_side_after_risk(self, bid, bpos):
        """Μετά από κίνδυνο σύγκρουσης: η πλευρά όπου στεκόμασταν ΔΕΝ μετράει ως
        ελεγμένη, ώστε να ξαναδοκιμαστεί (το πολύ RISK_RETRIES φορές).
        """
        cur = self.current_angle(bpos)
        sd = self.memory(bid).find(cur) if cur is not None else None
        if sd is None or not sd['visited'] or sd['plain']:
            return
        sd['risk'] = sd.get('risk', 0) + 1
        if sd['risk'] <= RISK_RETRIES:
            sd['visited'], sd['refine'], sd['peek'] = False, 0, 0
            print(f"   η πλευρά «{sd['label'][:30]}» θα ξαναδοκιμαστεί μετά την "
                  f"υποχώρηση ({sd['risk']}/{RISK_RETRIES})", flush=True)

    def retreat_from(self, bpos):
        """Υποχώρηση: πιο μακριά από τη βαλίτσα και πιο ψηλά, κοιτώντας την."""
        cam = self.listener.camera_position()
        if cam is None:
            return False
        dx, dy = cam[0]-bpos[0], cam[1]-bpos[1]
        n = math.hypot(dx, dy)
        if n < 1e-3:
            dx, dy, n = -bpos[0], -bpos[1], max(1e-3, math.hypot(bpos[0], bpos[1]))
        ux, uy = dx/n, dy/n
        for back, up in ((0.15, 0.10), (0.10, 0.15), (0.20, 0.05)):
            c = (cam[0] + ux*back, cam[1] + uy*back, cam[2] + up)
            if self.move_to(c, bpos, f"υποχώρηση (κίνδυνος σύγκρουσης) "
                                     f"[+{back:.2f}m, +{up:.2f}m]"):
                return True
        return self.elevate_view(bpos, "υποχώρηση σε ευρύ πλάνο")

    def finish_search(self, bid, now):
        """Ελέγχθηκαν όλες οι πλευρές ΧΩΡΙΣ tag προορισμού -> τέλος ΓΥΡΟΥ.
        Η βαλίτσα ΔΕΝ τελειώνει (τελειώνει μόνο με τον προορισμό), αλλά ΟΥΤΕ
        συνεχίζουμε από μνήμη: επιτήρηση ΜΠΡΟΣΤΑ, και νέος γύρος ΜΟΝΟ όταν η
        βαλίτσα ξαναφανεί στο κάδρο. Κρατάμε ροδάκια και την πλευρά του ΑΠΛΟΥ."""
        m = self.memory(bid)
        for _l in m.report(now):
            print(_l, flush=True)
        m.round = getattr(m, 'round', 1) + 1
        m.sides = [sd for sd in m.sides if sd['plain']]
        print(f"\n  *** {nice(bid)}: τέλος γύρου - ΔΕΝ βρέθηκε tag προορισμού.\n"
              f"      -> επιτήρηση ΜΠΡΟΣΤΑ. Γύρος {m.round} ΜΟΝΟ αν η βαλίτσα "
              f"ξαναφανεί (όχι από μνήμη) ***", flush=True)
        self.end_search()
        self.watch("(τέλος γύρου)")

    def end_search(self):
        """Τέλος αναζήτησης: τίποτα δεν συνεχίζει από μνήμη. Η επόμενη
        αναζήτηση ξεκινά ΜΟΝΟ από βαλίτσα που φαίνεται στο κάδρο."""
        self.target = None
        self.stuck = 0
        self.last_body = None
        self.dest_seen, self.dest_tries = None, 0
        self.watch_mode = 'forward'
        self.in_watch = False

    def near_done(self, p):
        """Κοντά σε βαλίτσα που ΤΕΛΕΙΩΣΕ; (τα χερούλια / ροδάκια της δεν
        ξεκινούν καινούργια αναζήτηση)"""
        return any(math.hypot(p[0]-self.mem[b].pos[0], p[1]-self.mem[b].pos[1])
                   < WHEEL_ASSIGN
                   for b in self.done_bodies
                   if b in self.mem and self.mem[b].pos is not None)

    def finish_dest(self, pos, now):
        """Τέλος παραμονής στον προορισμό -> επιτήρηση ΜΠΡΟΣΤΑ."""
        print(f"\n  *** ΕΠΙΒΕΒΑΙΩΘΗΚΕ: έμεινα {self.dest_cycles}/{DEST_STAY_CYCLES} "
              f"κύκλους στο tag προορισμού.\n"
              f"      Δημοσιεύτηκε στο /luggage/handle_pose_final\n"
              f"      -> επιτήρηση ΜΠΡΟΣΤΑ ***", flush=True)
        self.done_handles.append((pos, self.cycle))
        # Ποια βαλίτσα τελείωσε: ο στόχος, αλλιώς η γνωστή βαλίτσα δίπλα στο tag
        # (αν ο προορισμός φάνηκε π.χ. από την επιτήρηση, χωρίς ενεργό στόχο).
        owner = self.target
        if owner is None:
            _near = [(math.hypot(pos[0]-m.pos[0], pos[1]-m.pos[1]), b)
                     for b, m in self.mem.items() if m.pos is not None]
            _near = [x for x in _near if x[0] < WHEEL_ASSIGN]
            owner = min(_near)[1] if _near else None
        if owner is not None:
            self.done_bodies[owner] = self.cycle
            self.memory(owner).reset_search()
        self.reset_handle()
        self.end_search()
        self.watch("(προορισμός διαβάστηκε)")

    def recently_done(self, pos, now):
        """Χερούλι που ΗΔΗ διαβάσαμε, τους τελευταίους DONE_CYCLES κύκλους."""
        self.done_handles = [(p, c) for p, c in self.done_handles
                             if self.cycle - c < DONE_CYCLES]
        return any(math.dist(p, pos) < 0.20 for p, c in self.done_handles)

    # ---------- κύριος βρόχος ----------
    def run(self):
        """Ο κύριος βρόχος. Κάθε κύκλος:
          - παρατήρηση (observe), εμπόδια MoveIt, επανέλεγχος τελειωμένων βαλιτσών
          - log: τι φάνηκε + η μνήμη κάθε βαλίτσας
          - ΜΙΑ ενέργεια, με αυτή τη σειρά προτεραιότητας (κάθε `continue` = τέλος
            κύκλου):
              0. ΑΣΦΑΛΕΙΑ
              1. ΧΕΡΟΥΛΙ: προορισμός (παραμονή/τέλος) ή απλό (αποκλεισμός πλευράς)
                 + ο προορισμός χάθηκε -> μικρές διορθώσεις και τέλος
                 1β. μνήμη προορισμού που φάνηκε στο πέρασμα
              2. ΒΑΛΙΤΣΑ: μνήμη/ροδάκια (2α, 2β) -> διορθώσεις ίδιας πλευράς (2γ)
                 -> σειρά πλευρών (2γ2) -> γύρος όψεων όταν τα ροδάκια είναι
                 άγνωστα (2δ) -> «κολλημένος»
              3. ΤΙΠΟΤΑ: επιτήρηση
        Τα βήματα είναι σημειωμένα με τους ίδιους αριθμούς μέσα στον κώδικα.
        """
        while rclpy.ok():
            self.cycle += 1
            cycle = self.cycle
            if (self.rej_reach or self.rej_occl or self.rej_ik or self.rej_plan
                    or self.rej_clear):
                print(f"  [απορρίφθηκαν πόζες] εκτός εμβέλειας:{self.rej_reach}"
                      f"  αυτο-απόκρυψη:{self.rej_occl}  χωρίς IK:{self.rej_ik}"
                      f"  planner:{self.rej_plan}  πολύ κοντά σε βαλίτσα:"
                      f"{self.rej_clear}", flush=True)
            self.rej_reach, self.rej_occl, self.rej_ik, self.rej_plan = 0, 0, 0, 0
            self.rej_clear = 0
            det = self.observe()
            now = time.time()
            self.setup_ground()
            self.update_collision(det, now)
            # Βαλίτσα που τελείωσε (διαβάστηκε ο προορισμός): αγνοείται για
            # DONE_CYCLES κύκλους και μετά ΞΑΝΑΕΛΕΓΧΕΤΑΙ από την αρχή, με καθαρή
            # μνήμη (όλη η διαδικασία ξανά - για την προσομοίωση).
            for _b, _c in list(self.done_bodies.items()):
                if self.cycle - _c >= DONE_CYCLES:
                    del self.done_bodies[_b]
                    self.mem.pop(_b, None)
                    print(f"  (πέρασαν {DONE_CYCLES} κύκλοι -> {nice(_b)} θα "
                          f"ξαναελεγχθεί από την αρχή)", flush=True)
            # Γνωστές βαλίτσες για τον έλεγχο «πολύ κοντά» στο move_to:
            # ορατές τώρα + ο στόχος από τη μνήμη.
            self.boxes = {b: (p, self.yaws.get(b, 0.0)) for b, p in det.items()
                          if b in BODY_IDS}
            if (self.target is not None and self.target not in self.boxes
                    and self.target in self.mem and self.mem[self.target].pos):
                self.boxes[self.target] = (self.mem[self.target].pos,
                                           self.mem[self.target].yaw)
            # ---- log κύκλου: τι φάνηκε και τι θυμόμαστε ----
            print(f"\n{'='*70}\nΚΥΚΛΟΣ {cycle}", flush=True)
            _vb = [b for b in det if b in BODY_IDS]
            _ref = (min(_vb, key=lambda b: reach(det[b])) if _vb else
                    (self.last_body if self.last_body is not None
                     and now - self.last_body_t < BODY_MEMORY else None))
            for _i in sorted(det.keys()):
                if _i in BODY_IDS:
                    L, W, H = BODY_IDS[_i]['dims']
                    print(f"  ΕΝΤΟΠΙΣΤΗΚΕ: {nice(_i)}  "
                          f"διαστάσεις {L:.2f}x{W:.2f}x{H:.2f} m", flush=True)
                elif _i in HANDLE_IDS:
                    print(f"  ΕΝΤΟΠΙΣΤΗΚΕ: {handle_desc(_i, _ref)}", flush=True)
                else:
                    print(f"  ΕΝΤΟΠΙΣΤΗΚΕ: {nice(_i)}", flush=True)
            if not det:
                print("  ΕΝΤΟΠΙΣΤΗΚΕ: τίποτα", flush=True)
            for _b in sorted(self.mem):
                if self.mem[_b].pos is not None and now - self.mem[_b].t < BODY_MEMORY:
                    for _ln in self.mem[_b].report(now):
                        print(_ln, flush=True)
            print('='*70, flush=True)

            # Τι είδαμε από την πλευρά που στεκόμαστε; -> στη μνήμη
            for _b in [b for b in det if b in BODY_IDS]:
                _a = self.current_angle(det[_b])
                if _a is not None:
                    self.memory(_b).saw(_a, set(det.keys()), now)

            # 0. ΑΣΦΑΛΕΙΑ
            risk = self.collision_risk(det)
            if risk:
                bid, sp, cn, cp = risk
                print(f"  !!! ΚΙΝΔΥΝΟΣ ΣΥΓΚΡΟΥΣΗΣ: {nice(bid)}\n"
                      f"      ταχύτητα {sp:.2f} m/s | απόσταση τώρα {cn:.2f}m\n"
                      f"      σε {PREDICT_T:.0f}s θα είναι {cp:.2f}m -> ΥΠΟΧΩΡΩ",
                      flush=True)
                # Η πλευρά όπου στεκόμασταν ΔΕΝ μετράει ως ελεγμένη: μετά την
                # υποχώρηση ξαναδοκιμάζεται (το πολύ RISK_RETRIES φορές).
                self.retry_side_after_risk(bid, det[bid])
                if not self.retreat_from(det[bid]):
                    self.in_watch = False
                    self.watch("(αποφυγή σύγκρουσης)")
                continue

            # 1. ΧΕΡΟΥΛΙ
            # Ποιο χερούλι είναι ο ΠΡΑΓΜΑΤΙΚΟΣ στόχος εξαρτάται από τη βαλίτσα
            # Τελειωμένες βαλίτσες δεν ξεκινούν ξανά αναζήτηση (ως τον επανέλεγχο).
            vis_b = [b for b in det if b in BODY_IDS and b not in self.done_bodies]
            if vis_b:
                cur_b = (self.target if self.target in vis_b
                         else min(vis_b, key=lambda b: reach(det[b])))
                self.last_body, self.last_body_t = cur_b, now
            elif (self.last_body is not None
                  and self.last_body not in self.done_bodies
                  and now - self.last_body_t < BODY_MEMORY):
                # Η βαλίτσα δεν φαίνεται ΤΩΡΑ, αλλά τη θυμόμαστε - οπότε
                # ξέρουμε ακόμα ποιο χερούλι είναι ο στόχος της.
                cur_b = self.last_body
                print(f"  (βαλίτσα εκτός κάδρου - χρησιμοποιώ τη μνήμη: "
                      f"{nice(cur_b)})", flush=True)
            elif (self.target is not None
                  and self.known_pos(self.target, det, now) is not None):
                cur_b = self.target
                print(f"  (βαλίτσα εκτός κάδρου - 6D pose από τη μνήμη: "
                      f"{nice(cur_b)})", flush=True)
            else:
                cur_b = None
            # ΚΑΘΟΛΙΚΟΙ - δεν εξαρτώνται από το ποια βαλίτσα βλέπουμε
            dest_id, plain_id = DEST_ID, PLAIN_ID

            # Χερούλια βαλίτσας που ΤΕΛΕΙΩΣΕ αγνοούνται (αλλιώς, από την
            # επιτήρηση, το απλό χερούλι της ξεκινούσε αναζήτηση από μνήμη).
            all_h = [h for h in HANDLE_IDS if h in det
                     and not self.recently_done(det[h], now)
                     and not self.near_done(det[h])]

            # Κάθε φορά που το tag ΠΡΟΟΡΙΣΜΟΥ περνάει από το κάδρο - έστω
            # τυχαία, έστω για μια στιγμή - κρατάμε πού ήταν (όχι αν τελείωσε).
            if DEST_ID in all_h:
                self.dest_seen = (det[DEST_ID], now, self.handle_normal(DEST_ID))
                self.dest_tries = 0

            if dest_id in all_h:
                hs = [dest_id]                      # ο πραγματικός στόχος
            elif (plain_id in all_h and cur_b is not None
                  and self.known_pos(cur_b, det, now) is not None):
                # ΑΠΛΟ χερούλι -> ένδειξη. Ψάξε στοχευμένα το tag προορισμού.
                # Αν η βαλίτσα δεν φαίνεται (κάμερα κολλητά στο πλάι), το
                # 6D pose έρχεται από τη ΜΝΗΜΗ - ΟΧΙ ευρύ πλάνο.
                hs = []
                ppos = det[plain_id]
                bpos_c = self.known_pos(cur_b, det, now)
                wl = [det[w] for w in WHEEL_IDS if w in det]
                print(f"  ΟΡΑΤΟ: {handle_desc(plain_id, cur_b)}\n"
                      f"    Δεν είναι ο στόχος -> ΔΕΝ το πλησιάζω.\n"
                      f"    ΨΑΧΝΩ: {handle_desc(dest_id, cur_b)}", flush=True)

                # ΣΗΜΑΝΤΙΚΟ: ΔΕΝ πλησιάζουμε το απλό χερούλι για καλύτερη θέα.
                # Ξέρουμε ήδη ό,τι χρειαζόμαστε (πού βρίσκεται) - κάθε επιπλέον
                # κίνηση προς αυτό είναι χαμένος χρόνος. Πάμε ΑΜΕΣΩΣ στον στόχο.
                _m = self.memory(cur_b)
                moved = False
                if _m.wheel_loc is None:
                    # Ροδάκια άγνωστα, αλλά το απλό είναι σε ΣΤΕΝΗ άκρη (τοπικά
                    # ±90°): χερούλι σε στενή άκρη είναι ΠΑΝΤΑ απέναντι από τα
                    # ροδάκια -> τα ροδάκια είναι στην ΑΛΛΗ στενή άκρη.
                    _pl = _m.loc(math.atan2(ppos[1]-bpos_c[1], ppos[0]-bpos_c[0]))
                    if abs(math.sin(_pl)) > math.cos(ANGLE_SAME):
                        _m.wheel_loc = -math.pi/2 if math.sin(_pl) > 0 else math.pi/2
                        _m.wheel_src = 'απέναντι από το χερούλι της στενής άκρης'
                        print("      ροδάκια άγνωστα -> είναι στην ΑΛΛΗ στενή άκρη "
                              "(απέναντι από το απλό χερούλι)", flush=True)
                # Η πλευρά του ΑΠΛΟΥ αποκλείεται ΜΟΝΙΜΑ (όχι μόνο όσο φαίνεται).
                _pa = math.atan2(ppos[1]-bpos_c[1], ppos[0]-bpos_c[0])
                if _m.plain_at(_pa, now):
                    print("      η πλευρά του ΑΠΛΟΥ αποκλείεται - δεν ξαναπάω εκεί",
                          flush=True)
                _sp = self.side_plan(cur_b, bpos_c)
                if _sp is not None:
                    # Ξέρουμε πού είναι τα ροδάκια -> ίδια σειρά με πάνω
                    # (απέναντι, ΚΟΝΤΙΝΗ μακριά, ΜΑΚΡΙΝΗ μακριά), ΧΩΡΙΣ την
                    # πλευρά όπου μόλις είδαμε το απλό χερούλι.
                    _targets = [(l, a) for l, a in _sp
                                if ang_diff(a, _pa) >= ANGLE_SAME]
                    print("      σειρά: " + " -> ".join(l for l, a in _targets),
                          flush=True)
                else:
                    _targets = self.search_dest_angles(cur_b, bpos_c, ppos,
                                                       len(wl), wl)
                for lbl, ang in _targets:
                    if _m.done_side(ang):
                        continue
                    if self.view_angle(cur_b, bpos_c, ang,
                                       f"προς ΠΡΟΟΡΙΣΜΟ: {lbl}"):
                        moved = True
                        break
                    self.note_fail(cur_b, ang, lbl)
                if moved:
                    continue
                if _sp is not None and all(_m.done_side(a) for _l, a in _sp):
                    self.finish_search(cur_b, now)
                    continue
                # Καμία στοχευμένη γωνία δεν δούλεψε -> ελεύθερη αναζήτηση
                print("   στοχευμένες γωνίες εξαντλήθηκαν -> ελεύθερη στροφή",
                      flush=True)
                if self.step_around(cur_b, bpos_c):
                    continue
            elif plain_id in all_h:
                # Βλέπουμε το ΑΠΛΟ χερούλι αλλά όχι το σώμα -> ξέρουμε ότι
                # υπάρχει βαλίτσα εκεί. Ευρύ πλάνο για να βρεθεί το σώμα,
                # ώστε να ξέρουμε τον άξονά της και πού να ψάξουμε.
                hs = []
                print(f"  ΟΡΑΤΟ: {handle_desc(plain_id, cur_b)} χωρίς σώμα\n"
                      f"    -> ευρύ πλάνο για να εντοπίσω τη βαλίτσα",
                      flush=True)
                if self.elevate_view(det[plain_id], "ευρύ πλάνο για βαλίτσα"):
                    continue
            else:
                hs = []

            # 1α. ΤΟ TAG ΠΡΟΟΡΙΣΜΟΥ ΦΑΙΝΕΤΑΙ -> η αναζήτηση έχει σταματήσει:
            #     παραμονή DEST_STAY_CYCLES κύκλους, το πολύ 1 μικρή διόρθωση,
            #     δημοσίευση, και μετά επιτήρηση (finish_dest).
            if hs:
                self.blind_cycles = 0
                hid = hs[0]
                pos = det[hid]
                # Νέο ίχνος ΜΟΝΟ αν άλλαξε η θέση (άλλο χερούλι). ΟΧΙ λόγω
                # χρόνου: ένας αργός κύκλος δεν πρέπει να μηδενίζει την παραμονή.
                if (self.handle_pos is None
                        or math.dist(self.handle_pos, pos) > HANDLE_TOL):
                    self.handle_first_t = now
                    self.dest_cycles, self.dest_fixed = 0, False
                    print("   (νέο ίχνος χερουλιού)", flush=True)
                self.handle_pos = pos
                self.handle_yaw = self.handle_normal(hid)
                self.relook = 0
                self.relook_st = {'refine': 0, 'peek': 0}
                self.listener.publish_handle(pos)
                self.dest_cycles += 1
                held = now - self.handle_first_t
                print(f"  >>> ΣΤΟΧΟΣ: {handle_desc(hid, cur_b)}\n"
                      f"      θέση ({pos[0]:.3f}, {pos[1]:.3f}, {pos[2]:.3f}) m\n"
                      f"      παραμονή: κύκλος {self.dest_cycles}/{DEST_STAY_CYCLES}"
                      f"  ({held:.0f}s)", flush=True)

                if self.dest_cycles >= DEST_STAY_CYCLES:
                    self.finish_dest(pos, now)
                    continue
                # Αν η βαλίτσα ΕΡΧΕΤΑΙ ΠΑΝΩ ΜΑΣ -> υποχώρηση ΧΩΡΙΣ να χαθεί
                # το χερούλι από το κάδρο. Αλλιώς -> προσέγγιση σε ασφαλή
                # απόσταση για καθαρή θέαση.
                # Αν η θέα είναι ΗΔΗ καλή, ΜΗΝ κινείσαι - κάθε περιττή κίνηση
                # χάνει χρόνο και ρισκάρει να μπει ο βραχίονας στο κάδρο.
                cam_now = self.listener.camera_position()
                if cam_now is not None:
                    dist_now = math.dist(cam_now, pos)
                    off_now = self.view_offset(cam_now, pos, hid)
                    # ΚΡΙΣΙΜΟ: δεν αρκεί η απόσταση. Μια λοξή θέα σε σωστή
                    # απόσταση έμενε «καλή» για πάντα - ο βραχίονας παρκάριζε
                    # στραβά και μετρούσε χρόνο επιβεβαίωσης που δεν ερχόταν,
                    # επειδή το ArUco δεν διάβαζε ποτέ το tag.
                    dist_ok = HANDLE_GOOD_MIN <= dist_now <= HANDLE_GOOD_MAX
                    ang_ok = off_now is None or off_now <= VIEW_PERP_TOL
                    _a = ('' if off_now is None
                          else f", λοξότητα {math.degrees(off_now):.0f}°")
                    if dist_ok and ang_ok and not self.closing_body(det):
                        print(f"   θέα καλή ({dist_now:.2f}m{_a}) - παραμονή, "
                              f"διαβάζω το tag", flush=True)
                        continue
                    if not self.dest_fixed and not self.closing_body(det):
                        # ΜΙΑ διόρθωση το πολύ, για face to face
                        self.dest_fixed = True
                        print(f"   θέα λοξή ή σε λάθος απόσταση ({dist_now:.2f}m{_a}) "
                              f"-> ΜΙΑ μικρή διόρθωση για face to face", flush=True)
                        if not self.nudge_to_front(pos, self.handle_yaw, cam_now):
                            print("   καμία μικρή διόρθωση εφικτή - μένω εδώ, "
                                  "διαβάζω το tag", flush=True)
                        continue

                closing = self.closing_body(det)
                if closing:
                    cb, cs = closing
                    print(f"   {BODY_IDS[cb]['name']} πλησιάζει ({cs:.2f}m/s) -> "
                          f"υποχώρηση κρατώντας το χερούλι στο κάδρο", flush=True)
                    if self.retreat_keeping_view(pos, "υποχώρηση με θέα χερουλιού"):
                        continue
                    self.view_handle(pos, self.handle_yaw)
                    continue
                # Χωρίς θέση κάμερας, ή η διόρθωση έγινε ήδη -> ΜΕΝΟΥΜΕ εδώ.
                print("   παραμονή εδώ, διαβάζω το tag", flush=True)
                continue

            # Το tag προορισμού ΒΡΕΘΗΚΕ και μετά ΧΑΘΗΚΕ. Η αναζήτηση ΕΧΕΙ
            # ΣΤΑΜΑΤΗΣΕΙ: ΔΕΝ πάμε σε άλλες πλευρές. Έως MAX_RELOOK μικρές
            # διορθώσεις εκεί (από την τωρινή θέση) και μετά τέλος βαλίτσας ->
            # επιτήρηση ΜΠΡΟΣΤΑ, με την τελευταία θέση του tag (έχει ήδη δημοσιευτεί).
            if self.handle_pos is not None:
                self.relook += 1
                self.dest_cycles += 1
                if self.relook > MAX_RELOOK or self.dest_cycles >= DEST_STAY_CYCLES:
                    print("   το tag προορισμού χάθηκε, αλλά ΕΙΧΕ ΒΡΕΘΕΙ -> τέλος "
                          "αναζήτησης (όχι άλλες πλευρές)", flush=True)
                    self.finish_dest(self.handle_pos, now)
                    continue
                print(f"   το tag προορισμού χάθηκε - μικρή διόρθωση εδώ "
                      f"({self.relook}/{MAX_RELOOK})  [παραμονή "
                      f"{self.dest_cycles}/{DEST_STAY_CYCLES}]", flush=True)
                if not self.small_correction(self.handle_pos, self.handle_yaw,
                                             self.relook_st, MAX_RELOOK,
                                             "το tag χάθηκε - μικρή διόρθωση"):
                    print("   καμία μικρή διόρθωση εφικτή - μένω εδώ", flush=True)
                continue

            # 1β. ΜΝΗΜΗ ΠΡΟΟΡΙΣΜΟΥ - είδαμε το tag κάποια στιγμή, γύρνα εκεί
            if self.dest_seen is not None:
                dpos, dt, dyaw = self.dest_seen
                if now - dt > DEST_MEMORY or self.dest_tries >= DEST_MAX_TRIES:
                    self.dest_seen = None
                elif not self.recently_done(dpos, now):
                    self.dest_tries += 1
                    print(f"  [ΜΝΗΜΗ] είχα δει {nice(DEST_ID)} πριν {now-dt:.0f}s "
                          f"-> επιστροφή εκεί ({self.dest_tries}/{DEST_MAX_TRIES})",
                          flush=True)
                    if self.view_handle(dpos, dyaw):
                        continue
                    self.dest_seen = None

            # 2. ΒΑΛΙΤΣΑ
            bodies = {i: p for i, p in det.items() if i in BODY_IDS}
            vis_avail = {b: p for b, p in bodies.items()
                         if b not in self.done_bodies and reach(p) <= WORKABLE_DIST}
            too_far = {b: p for b, p in bodies.items()
                       if b not in self.done_bodies and reach(p) > WORKABLE_DIST}
            if too_far and not vis_avail:
                names = ', '.join(f"{BODY_IDS[b]['name']}@{reach(p):.2f}m"
                                  for b, p in too_far.items())
                print(f"   (μακριά, αγνοούνται: {names})", flush=True)
            wheels = {w: det[w] for w in WHEEL_IDS if w in det}

            # --- ΕΝΗΜΕΡΩΣΗ ΜΝΗΜΗΣ: 6D pose κάθε ορατής βαλίτσας ---
            # ΔΕΝ σβήνει πλευρές/ροδάκια: είναι τοπικές γωνίες, ισχύουν ακόμα.
            for _b, _p in bodies.items():
                if self.memory(_b).update(_p, self.yaws.get(_b, 0.0), now,
                                          self.quats.get(_b)):
                    print(f"   ({nice(_b)} μετακινήθηκε -> νέο 6D pose στη "
                          f"μνήμη)", flush=True)

            # Η βαλίτσα-στόχος δεν φαίνεται ΤΩΡΑ (π.χ. κάμερα κολλητά στο πλάι)
            # αλλά τη θυμόμαστε -> η αναζήτηση συνεχίζει με το pose της μνήμης.
            avail = dict(vis_avail)
            if (self.target is not None and self.target not in avail
                    and self.target not in self.done_bodies):
                _kp = self.known_pos(self.target, det, now)
                if _kp is not None:
                    avail[self.target] = _kp

            # Πού είναι τα ροδάκια ως προς τη βαλίτσα τους (ΤΟΠΙΚΑ):
            #   2 ορατά -> κατεύθυνση ροδακιών (ανανεώνεται όποτε φανούν ξανά)
            #   1 ορατό -> κρατάμε μόνο αυτό (για πλησίασμα / εκτίμηση)
            if wheels and avail:
                _wp = list(wheels.values())
                _wx = sum(q[0] for q in _wp)/len(_wp)
                _wy = sum(q[1] for q in _wp)/len(_wp)
                _b = min(avail, key=lambda b: math.hypot(_wx-avail[b][0],
                                                         _wy-avail[b][1]))
                _bp = avail[_b]
                if math.hypot(_wx-_bp[0], _wy-_bp[1]) < WHEEL_ASSIGN:
                    _m = self.memory(_b)
                    _l = _m.loc(math.atan2(_wy-_bp[1], _wx-_bp[0]))
                    if len(_wp) >= 2:
                        if _m.wheel_loc is None:
                            print(f"   2 ροδάκια -> κατεύθυνση ροδακιών στη μνήμη "
                                  f"(τοπικά {math.degrees(_l):+.0f}°)", flush=True)
                        _m.wheel_loc, _m.wheel_src = _l, '2 ροδάκια'
                    else:
                        _m.one_wheel = (_l, _wp[0])

            # Πού είδαμε το ΑΠΛΟ χερούλι (τοπικά ως προς τον άξονα)
            if PLAIN_ID in det and cur_b is not None and cur_b in avail:
                _m = self.memory(cur_b)
                _m.plain_loc = _m.loc(math.atan2(det[PLAIN_ID][1]-avail[cur_b][1],
                                                 det[PLAIN_ID][0]-avail[cur_b][0]))

            # 2α. Ροδάκια ΑΓΝΩΣΤΗΣ βαλίτσας -> ευρύ πλάνο. Ροδάκια βαλίτσας που
            # φαίνεται ή που ΤΕΛΕΙΩΣΕ δεν είναι λόγος για ευρύ πλάνο (αλλιώς,
            # μετά το τέλος, ανέβαινε ξανά και ξανά για τη ίδια βαλίτσα).
            _known = list(bodies.values()) + [
                self.mem[b].pos for b in self.done_bodies
                if b in self.mem and self.mem[b].pos is not None]
            free_wheels = {w: p for w, p in wheels.items()
                           if all(math.hypot(p[0]-k[0], p[1]-k[1]) >= WHEEL_ASSIGN
                                  for k in _known)}
            if not avail and free_wheels:
                self.blind_cycles = 0
                wp = list(free_wheels.values())
                mid = (sum(p[0] for p in wp)/len(wp),
                       sum(p[1] for p in wp)/len(wp),
                       sum(p[2] for p in wp)/len(wp))
                print(f"ΚΟΜΜΑΤΙ ΒΑΛΙΤΣΑΣ ({len(wp)} ροδάκι) χωρίς body tag "
                      f"-> ανύψωση για ευρύ πλάνο", flush=True)
                self.elevate_view(mid, "ευρύ πλάνο για εντοπισμό βαλίτσας")
                continue

            if avail:
                self.blind_cycles = 0
                if self.target in avail:
                    if self.target in vis_avail:
                        self.last_seen = now
                elif self.target is None or (now-self.last_seen) > LOST_GRACE:
                    cand = {b: p for b, p in avail.items()
                            if reach(p) <= MAX_REACH} or avail
                    self.target = min(cand, key=lambda b: reach(cand[b]))
                    # Η μνήμη της βαλίτσας ΔΕΝ σβήνεται: ό,τι ξέρουμε γι' αυτή ισχύει.
                    print(f"  [ΝΕΟΣ ΣΤΟΧΟΣ] {nice(self.target)}", flush=True)
                    self.last_seen = now

                bid = self.target if self.target in avail else min(
                    avail, key=lambda b: reach(avail[b]))
                bpos = avail[bid]
                m = self.memory(bid)
                nv = sum(1 for p in wheels.values()
                         if math.hypot(p[0]-bpos[0], p[1]-bpos[1]) < WHEEL_ASSIGN)
                _mem_txt = ("" if bid in bodies
                            else f"  [ΑΠΟ ΜΝΗΜΗ, πριν {now-m.t:.0f}s]")

                vx, vy = self.velocity(bid)
                print(f"  ΒΑΛΙΤΣΑ: {nice(bid)}{_mem_txt}\n"
                      f"    θέση      ({bpos[0]:.2f}, {bpos[1]:.2f}, {bpos[2]:.2f}) m\n"
                      f"    στροφή    {math.degrees(self.yaws.get(bid,0.0)):.0f}°\n"
                      f"    απόσταση  {reach(bpos):.2f} m από τη βάση\n"
                      f"    ταχύτητα  {math.hypot(vx,vy):.2f} m/s\n"
                      f"    ροδάκια ορατά: {nv}", flush=True)

                # 2β. ΚΑΤΕΥΘΥΝΣΗ ΡΟΔΑΚΙΩΝ - ΜΟΝΟ όσο είναι ΑΓΝΩΣΤΗ
                #   2 ροδάκια -> ήδη γνωστή (πιο πάνω) -> κατευθείαν απέναντι
                #   αλλιώς    -> ΕΥΡΥ ΠΛΑΝΟ (μία φορά)
                #   μετά 1    -> ΛΙΓΟ πιο κοντά για το 2ο (μία φορά, ΜΟΝΟ τότε)
                #   ακόμα 1   -> εκτίμηση από το 1 ροδάκι + τον άξονα της βαλίτσας
                #   κανένα    -> γύρος στις πλευρές μέχρι να φανούν
                # Μόλις η κατεύθυνση γίνει γνωστή, τίποτα από αυτά δεν ξαναγίνεται.
                if m.wheel_loc is None:
                    if not m.wide_done:
                        m.wide_done = True
                        print(f"   ροδάκια ορατά: {nv} (<2), κατεύθυνση άγνωστη "
                              f"-> ΕΥΡΥ ΠΛΑΝΟ (μία φορά)", flush=True)
                        if self.elevate_view(bpos, "ευρύ πλάνο για ροδάκια"):
                            continue
                    if m.one_wheel is not None and not m.approach_done:
                        m.approach_done = True
                        print("   μόνο 1 ροδάκι -> ΛΙΓΟ πιο κοντά για να φανεί "
                              "και το 2ο (μία φορά)", flush=True)
                        if self.approach_wheel_end(bid, bpos, m):
                            continue
                    if m.one_wheel is not None:
                        m.wheel_loc = (math.pi/2 if math.sin(m.one_wheel[0]) >= 0
                                       else -math.pi/2)
                        m.wheel_src = '1 ροδάκι + άξονας βαλίτσας'
                        print(f"   το 2ο ροδάκι δεν φάνηκε -> ροδάκια στη ΣΤΕΝΗ "
                              f"άκρη προς το ροδάκι που είδαμε (τοπικά "
                              f"{math.degrees(m.wheel_loc):+.0f}°)", flush=True)
                    elif 'no_wheels' not in m.flags:
                        m.flags.add('no_wheels')
                        print("   κανένα ροδάκι ούτε στο ευρύ πλάνο -> γύρος στις "
                              "πλευρές μέχρι να φανούν", flush=True)

                # 2γ. ΕΠΙΜΟΝΗ ΣΤΗΝ ΤΡΕΧΟΥΣΑ ΠΛΕΥΡΑ πριν την εγκαταλείψουμε.
                # Το tag μπορεί να φαίνεται και απλώς να μην το πιάνει το
                # ArUco: πλησιάζουμε και ισιώνουμε πρώτα.
                if self.refine_current(bid, bpos):
                    continue

                # 2γ2. ΚΑΤΕΥΘΥΝΣΗ ΡΟΔΑΚΙΩΝ ΓΝΩΣΤΗ -> ΣΤΑΘΕΡΗ ΣΕΙΡΑ ΠΛΕΥΡΩΝ
                #   1) ΑΠΕΝΑΝΤΙ από τα ροδάκια (στενή άκρη)
                #   2) η ΠΙΟ ΚΟΝΤΙΝΗ / ευκολότερη ΜΑΚΡΙΑ πλευρά
                #   3) η άλλη ΜΑΚΡΙΑ πλευρά
                # Η μεριά ΤΩΝ ΡΟΔΑΚΙΩΝ δεν μπαίνει ποτέ στη λίστα.
                # Από τη ΜΝΗΜΗ: από το «απέναντι» τα ροδάκια δεν φαίνονται,
                # αλλά ξέρουμε πού είναι.
                plan = self.side_plan(bid, bpos)
                if plan is not None:
                    _m = self.memory(bid)
                    moved = False
                    for _i, (lbl, a) in enumerate(plan, 1):
                        if _m.done_side(a):
                            continue
                        print(f"   ΣΕΙΡΑ {_i}/3 -> {lbl} "
                              f"({math.degrees(a):.0f}°)", flush=True)
                        if self.view_angle(bid, bpos, a, lbl):
                            moved = True
                            break
                        self.note_fail(bid, a, lbl)
                    if moved:
                        continue
                    if all(_m.done_side(a) for _l, a in plan):
                        # Και οι 3 ελεγμένες (ή απλό / ανέφικτες) -> ΤΕΛΟΣ
                        self.finish_search(bid, now)
                        continue

                # 2δ. Σταδιακή στροφή (εφεδρικό, όταν δεν φαίνονται ροδάκια)
                if self.step_around(bid, bpos):
                    continue

                self.stuck += 1
                print(f"   [!] κύκλος χωρίς κίνηση ({self.stuck}/{STUCK_LIMIT})",
                      flush=True)
                if self.stuck >= STUCK_LIMIT:
                    print("   ~~~ κολλημένος σε αυτή τη βαλίτσα -> ενεργή αναζήτηση "
                          "(η μνήμη πλευρών ΜΕΝΕΙ)", flush=True)
                    self.target = None
                    self.stuck = 0
                    self.in_watch = False
                    self.toggle_watch()
                    self.watch("(εγκατάλειψη απρόσιτης βαλίτσας)")
                continue

            if bodies:
                self.blind_cycles += 1
                print(f"καμία αξιοποιήσιμη βαλίτσα ({self.blind_cycles}) -> επιτήρηση",
                      flush=True)
                if self.blind_cycles >= BLIND_SWITCH:
                    self.toggle_watch()
                self.watch("(αναμονή προσιτής βαλίτσας)")
                continue

            # 3. ΤΙΠΟΤΑ
            if self.target is not None and (now-self.last_seen) > LOST_GRACE:
                self.target = None
            self.blind_cycles += 1
            print(f"τίποτα ορατό ({self.blind_cycles}) -> επιτήρηση "
                  f"{'ΜΠΡΟΣΤΑ' if self.watch_mode=='forward' else 'ΠΛΑΓΙΑ ΔΕΞΙΑ'}",
                  flush=True)
            if self.blind_cycles >= BLIND_SWITCH:
                self.toggle_watch()
            self.watch()


