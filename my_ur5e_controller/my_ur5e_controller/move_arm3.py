# --- ΡΟΛΟΣ ΧΕΡΟΥΛΙΩΝ ΑΝΑ ΒΑΛΙΤΣΑ ---
# Κάθε βαλίτσα έχει ΔΥΟ χερούλια: ένα ΑΠΛΟ και ένα με TAG ΠΡΟΟΡΙΣΜΟΥ.
# Στόχος είναι ΠΑΝΤΑ το tag προορισμού. Το απλό είναι ΕΝΔΕΙΞΗ: όταν το
# βρούμε, ξέρουμε ότι υπάρχει βαλίτσα και ψάχνουμε στοχευμένα το άλλο.
# =============================================================================
#  ΡΟΛΟΣ ΤΩΝ ΔΥΟ ΧΕΡΟΥΛΙΩΝ  <<< ΑΛΛΑΞΕ ΜΟΝΟ ΑΥΤΗ ΤΗ ΓΡΑΜΜΗ >>>
