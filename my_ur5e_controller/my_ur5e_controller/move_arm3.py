def reach(p):
    """Απόσταση σημείου από την αρχή του BASE_FRAME (βάση του βραχίονα)."""
    return math.sqrt(p[0]**2 + p[1]**2 + p[2]**2)


def quat_mul(a, b):
    """a (x,y,z,w) ⊗ b (x,y,z,w)."""
    ax, ay, az, aw = a
    bx, by, bz, bw = b
    return (aw*bx + ax*bw + ay*bz - az*by,
            aw*by - ax*bz + ay*bw + az*bx,
            aw*bz + ax*by - ay*bx + az*bw,
            aw*bw - ax*bx - ay*by - az*bz)


def quat_axes(q):
    """Άξονες της ΚΑΜΕΡΑΣ στο base_link, από το quaternion της.

    Σύμβαση gemini_camera_link (φυσική, όχι optical):
        +X = εμπρός (βάθος),  +Y = αριστερά,  +Z = πάνω
    Άρα: εμπρός = 1η στήλη, δεξιά = −2η στήλη, πάνω = 3η στήλη.

    Χρειάζονται οι ΠΡΑΓΜΑΤΙΚΕΣ στήλες: με ελεύθερο roll το κάδρο γυρίζει
    και δεν ισχύει πια η παραδοχή «πάνω = παγκόσμιο z».
    """
    x, y, z, w = q
    fwd = (1-2*(y*y+z*z), 2*(x*y+w*z),   2*(x*z-w*y))
    lft = (2*(x*y-w*z),   1-2*(x*x+z*z), 2*(y*z+w*x))
    up  = (2*(x*z+w*y),   2*(y*z-w*x),   1-2*(x*x+y*y))
    return fwd, (-lft[0], -lft[1], -lft[2]), up


def look_at_quaternion(cam, target, roll=0.0):
    """+X της κάμερας προς τον στόχο, με ΕΛΕΥΘΕΡΟ roll.

    Το roll είναι περιστροφή γύρω από τον ίδιο τον άξονα θέασης: αλλάζει
    μόνο πώς είναι γυρισμένη η εικόνα, όχι τι περιλαμβάνει. Το ArUco
    διαβάζει το tag σε οποιαδήποτε περιστροφή, οπότε μπορούμε να το
    εκμεταλλευτούμε για να βρούμε λύση IK εκεί που με roll=0 δεν υπήρχε.
    """
    dx, dy, dz = target[0]-cam[0], target[1]-cam[1], target[2]-cam[2]
    n = math.sqrt(dx*dx + dy*dy + dz*dz)
    if n < 1e-6:
        return (0.0, 0.0, 0.0, 1.0)
    dx, dy, dz = dx/n, dy/n, dz/n
    yaw = math.atan2(dy, dx)
    pitch = -math.asin(max(-1.0, min(1.0, dz)))
    cy, sy = math.cos(yaw/2), math.sin(yaw/2)
    cp, sp = math.cos(pitch/2), math.sin(pitch/2)
    q = (-sp*sy, sp*cy, cp*sy, cp*cy)
    if abs(roll) < 1e-9:
        return q
    cr, sr = math.cos(roll/2), math.sin(roll/2)
    return quat_mul(q, (sr, 0.0, 0.0, cr))   # roll γύρω από τον άξονα θέασης


def tag_normal_az(q):
    """Αζιμούθιο της ΚΑΘΕΤΟΥ του tag - πού «κοιτάζει» - στο base_link.

    ΓΙΑΤΙ ΟΧΙ Ο yaw: ο yaw από quaternion (σύμβαση ZYX) ταυτίζεται με τη
    διεύθυνση της καθέτου ΜΟΝΟ για tag που κείτεται επίπεδο. Για ΟΡΘΙΟ tag
    - όπως τα χερούλια, με οριζόντια κάθετο - ο yaw βγαίνει μετατοπισμένος
    κατά ακριβώς 90°, οπότε η κάμερα πάει να σταθεί στην ΑΚΜΗ του tag: το
    βλέπει εφαπτομενικά και το ArUco δεν το πιάνει, ενώ οπτικά φαίνεται.

    Η κάθετος είναι η τρίτη στήλη του πίνακα περιστροφής.
    Επιστρέφει None αν η κάθετος είναι σχεδόν κατακόρυφη (επίπεδο tag),
    οπότε δεν ορίζεται αζιμούθιο.
    """
    if q is None:
        return None
    x, y, z, w = q
    nx = 2.0*(x*z + w*y)
    ny = 2.0*(y*z - w*x)
    if math.hypot(nx, ny) < 0.15:      # κάθετος ~κατακόρυφη
        return None
    return math.atan2(ny, nx)


def ang_diff(a, b):
    """Απόλυτη γωνιακή διαφορά σε [0, π], ανεξάρτητα από το 2π."""
    d = (a - b + math.pi) % (2*math.pi) - math.pi
    return abs(d)


def self_view_angle(cam, look):
    """Γωνία ανάμεσα στη διεύθυνση ΘΕΑΣΗΣ και στη διεύθυνση κάμερα->ΒΑΣΗ.

    Ο βραχίονας εκτείνεται από τη βάση προς την κάμερα, άρα βρίσκεται πάντα
    κάπου στη διεύθυνση κάμερα->βάση. Αν η κάμερα κοιτάει ΠΡΟΣ τα εκεί
    (μικρή γωνία) βλέπει τον ίδιο της τον βραχίονα.
      180° -> κοιτάει τελείως αντίθετα από τη βάση, καθαρό κάδρο
        0° -> κοιτάει κατευθείαν στη βάση, ο βραχίονας γεμίζει το κάδρο
    """
    vx, vy, vz = look[0]-cam[0], look[1]-cam[1], look[2]-cam[2]
    vn = math.sqrt(vx*vx + vy*vy + vz*vz)
    cn = reach(cam)
    if vn < 1e-6 or cn < 1e-6:
        return math.pi
    dot = (vx*(-cam[0]) + vy*(-cam[1]) + vz*(-cam[2])) / (vn*cn)
    return math.acos(max(-1.0, min(1.0, dot)))


