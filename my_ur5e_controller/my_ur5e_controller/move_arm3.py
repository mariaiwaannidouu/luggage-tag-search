# Εκεί ΔΕΝ υπάρχει ποτέ χερούλι - κάθε κίνηση προς τα εκεί είναι χαμένος χρόνος.
WHEEL_EXCLUDE = math.radians(70)

# Διαστάσεις (L, W, H) για βαλίτσα με άγνωστο id σώματος (εφεδρικό).
