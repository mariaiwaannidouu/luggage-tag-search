#  Ισχύει για ΟΛΕΣ τις βαλίτσες. Άλλαξέ το και ξανατρέξε - τίποτε άλλο
#  δεν χρειάζεται.
# =============================================================================
DEST_ON_LONG_SIDE = True

# Ο ρόλος είναι ο ΙΔΙΟΣ σε όλες τις βαλίτσες, άρα ΔΕΝ χρειάζεται να ξέρουμε
