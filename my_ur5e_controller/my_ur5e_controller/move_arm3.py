def nice(i):
    """Περιγραφικό όνομα για log. Επιστρέφει π.χ. 'χερούλι ΠΛΑΙ (id6)'."""
    return f"{NICE.get(i, f'άγνωστο')} (id{i})"


# Πού βρίσκεται ΦΥΣΙΚΑ κάθε χερούλι πάνω στη βαλίτσα.
# ΠΡΟΣΟΧΗ: χρησιμοποιείται ΜΟΝΟ για ευανάγνωστα logs. Ο αλγόριθμος
# υπολογίζει τη θέση γεωμετρικά (handle_face) και ΔΕΝ βασίζεται σε αυτό.
HANDLE_PLACE = {3: 'στενή άκρη', 6: 'μακριά πλευρά'}


def role_of(hid, bid=None):
    """Τι ΡΟΛΟ έχει το χερούλι hid;

    Ο ρόλος είναι ΚΑΘΟΛΙΚΟΣ (βλ. DEST_ON_LONG_SIDE) - ίδιος σε κάθε
    βαλίτσα. Το bid μένει στην υπογραφή μόνο για συμβατότητα κλήσεων.
    """
    if hid == DEST_ID:
        return 'ΠΡΟΟΡΙΣΜΟΥ'
    if hid == PLAIN_ID:
        return 'ΑΠΛΟ'
    return 'ΑΓΝΩΣΤΟΣ ΡΟΛΟΣ'


def handle_desc(hid, bid=None):
    """π.χ. 'χερούλι ΠΛΑΙ (στενή άκρη) [ΠΡΟΟΡΙΣΜΟΥ]'"""
    place = HANDLE_PLACE.get(hid, '')
    txt = f"{NICE.get(hid, '?')}"
    if place:
        txt += f" ({place})"
    if bid is not None:
        txt += f" [{role_of(hid, bid)}]"
    return txt


def nice_list(ids):
    """Λίστα ids -> ευανάγνωστο κείμενο για το log."""
