# =============================================================================
#  ΡΥΘΜΙΣΕΙΣ ΒΡΑΧΙΟΝΑ  (ό,τι αλλάζει όταν αλλάζει ο βραχίονας / η κάμερα)
# -----------------------------------------------------------------------------
#  Οι τιμές εδώ είναι για τον UR5e της προσομοίωσης. Για ΑΛΛΟ βραχίονα (π.χ.
#  ABB GoFa 12) ΔΕΝ αλλάζεις τον κώδικα: γράφεις ένα YAML (δες config/ur5e.yaml
