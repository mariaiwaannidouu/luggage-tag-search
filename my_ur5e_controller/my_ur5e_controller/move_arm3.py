#!/usr/bin/env python3
"""
move_arm3.py - Αναζήτηση του ΧΕΡΟΥΛΙΟΥ ΠΡΟΟΡΙΣΜΟΥ βαλίτσας με βραχίονα που
έχει κάμερα βάθους στο άκρο του (ROS 2 Jazzy + MoveItPy).

ΤΙ ΚΑΝΕΙ
    Ο βραχίονας (τώρα UR5e σε Gazebo - τελικός στόχος ABB GoFa 12) επιτηρεί
    έναν διάδρομο με βαλίτσες. Κάθε βαλίτσα έχει ArUco tags:
        ids 0/1/2 : tag του ΣΩΜΑΤΟΣ, στην ΚΟΡΥΦΗ  -> θέση + στροφή (6D pose)
        ids 4/5   : τα δύο ΡΟΔΑΚΙΑ, σε μία ΣΤΕΝΗ άκρη
        id 3 / 6  : τα δύο ΧΕΡΟΥΛΙΑ - ένα ΑΠΛΟ και ένα με tag ΠΡΟΟΡΙΣΜΟΥ
    Στόχος: να βρει και να διαβάσει ΜΕΤΩΠΙΚΑ το tag ΠΡΟΟΡΙΣΜΟΥ και να
    δημοσιεύσει τη θέση του. Ο βραχίονας ΔΕΝ ξέρει εκ των προτέρων σε ποια
    πλευρά της βαλίτσας είναι - το ψάχνει.

ΣΥΝΔΕΣΕΙΣ
    είσοδος : /luggage/tag_detections  (visualization_msgs/MarkerArray) από
              τον ανιχνευτή (aruco_multi_detector.py). marker.id = id tag,
              marker.pose = θέση/προσανατολισμός ΣΤΟ BASE_FRAME.
              TF BASE_FRAME -> CAMERA_LINK (πού είναι τώρα η κάμερα).
    έξοδος  : /luggage/handle_pose_final (geometry_msgs/PoseStamped)
              /collision_object - δάπεδο και βαλίτσες ως εμπόδια του MoveIt
    κίνηση  : MoveItPy, planning group PLANNING_GROUP. ΟΛΟΙ οι στόχοι αφορούν
              το CAMERA_LINK (πού στέκεται η κάμερα και πού κοιτάζει).

Ο ΚΥΚΛΟΣ  (Mission.run)
    Κάθε κύκλος: παρατήρηση ~1 s, μετά ΜΙΑ ενέργεια - η πρώτη που ισχύει:
    0. ΑΣΦΑΛΕΙΑ   κάμερα πολύ κοντά σε βαλίτσα -> υποχώρηση, ξανά η ίδια πλευρά
    1. ΧΕΡΟΥΛΙΑ   tag ΠΡΟΟΡΙΣΜΟΥ ορατό (έστω 1 καρέ) -> η αναζήτηση ΣΤΑΜΑΤΑ:
                  μένει DEST_STAY_CYCLES κύκλους (το πολύ 1 μικρή διόρθωση για
                  μετωπική θέα), δημοσιεύει, επιτήρηση ΜΠΡΟΣΤΑ.
                  ΑΠΛΟ χερούλι -> η πλευρά του αποκλείεται μόνιμα, συνέχεια.
    2. ΒΑΛΙΤΣΑ    αναζήτηση γύρω της:
                  α) κατεύθυνση ροδακιών, ΜΟΝΟ όσο είναι άγνωστη: 2 ορατά ->
                     γνωστή· αλλιώς ευρύ πλάνο (1 φορά)· 1 ροδάκι -> λίγο πιο
                     κοντά (1 φορά)· αλλιώς εκτίμηση ή γύρος στις πλευρές
                  β) σειρά πλευρών: ΑΠΕΝΑΝΤΙ από τα ροδάκια -> ΚΟΝΤΙΝΗ μακριά ->
                     ΜΑΚΡΙΝΗ μακριά (ακόμα και με πλήρες τέντωμα). ΠΟΤΕ η μεριά
                     των ροδακιών.
                  γ) σε κάθε πλευρά: μετωπική θέα πρώτα· μικρές διορθώσεις μόνο
                     αν η θέα είναι λοξή· ανέφικτη -> το πολύ SIDE_MAX_FAILS
                  δ) όλες ελεγμένες χωρίς προορισμό -> τέλος γύρου, επιτήρηση·
                     νέος γύρος ΜΟΝΟ όταν η βαλίτσα ξαναφανεί
    3. ΤΙΠΟΤΑ     επιτήρηση, εναλλάξ ΜΠΡΟΣΤΑ / ΠΛΑΓΙΑ ΔΕΞΙΑ

ΒΑΣΙΚΕΣ ΕΝΝΟΙΕΣ
    Μνήμη βαλίτσας (SuitcaseMemory): 6D pose, κατεύθυνση ροδακιών και ποιες
        πλευρές ελέγχθηκαν - σε ΤΟΠΙΚΕΣ γωνίες (ως προς τον άξονα της
        βαλίτσας), ώστε να ισχύουν κι αν η βαλίτσα γυρίσει. Όσο κρατά μια
        αναζήτηση, αν το tag του σώματος δεν φαίνεται (κάμερα κολλητά στο
        πλάι), συνεχίζουμε με τη μνήμη. Μετά το τέλος, ΟΧΙ.
    Γεωμετρία βαλίτσας: διαστάσεις (L, W, H) από BODY_IDS. Η γωνία yaw του
        tag σώματος δείχνει προς ΜΑΚΡΙΑ πλευρά· οι ΣΤΕΝΕΣ άκρες (εκεί τα
        ροδάκια και το ένα χερούλι) είναι στις yaw ± 90°.
    Κίνηση (Mission.move_to): στόχος = θέση κάμερας + σημείο που κοιτάζει.
        Ελεύθερη περιστροφή γύρω από τον άξονα θέασης (ROLL_OPTIONS - το
        ArUco διαβάζει και ανάποδα), IK με σπόρο την τωρινή στάση, επιλογή της
        λύσης με τη ΜΙΚΡΟΤΕΡΗ κίνηση αρθρώσεων, έλεγχος ότι ο βραχίονας δεν
        μπαίνει στο κάδρο (self_occludes) και ότι η κάμερα δεν πλησιάζει
        βαλίτσα (clearance). Ο planner πηγαίνει ΑΚΡΙΒΩΣ στη στάση που ελέγχθηκε.
    Μονάδες: μέτρα, δευτερόλεπτα, ακτίνια. Συντεταγμένες στο BASE_FRAME.

ΕΚΤΕΛΕΣΗ
    ros2 launch my_ur5e_controller run_move_arm3.launch.py [robot_config:=x.yaml]
    (Gazebo, MoveIt και ανιχνευτής ξεκινούν χωριστά - δες README.md)

ΑΛΛΟΣ ΒΡΑΧΙΟΝΑΣ (π.χ. ABB GoFa 12)
    ΔΕΝ αλλάζεις αυτό το αρχείο: config/gofa12.yaml + PORTING_GOFA12.md.
    Τι ρυθμίζεται με YAML: ROBOT_CONFIG_KEYS (πιο κάτω).

ΜΟΝΟ ΓΙΑ ΤΗΝ ΠΡΟΣΟΜΟΙΩΣΗ (να ξαναδούν στο πραγματικό σύστημα)
    DEST_ON_LONG_SIDE : ποιο id είναι ο προορισμός (6 ή 3). Η λογική
                        αναζήτησης ΔΕΝ το χρησιμοποιεί για να ξέρει πού να ψάξει.
    DONE_CYCLES       : επανέλεγχος της ΙΔΙΑΣ βαλίτσας μετά από 10 κύκλους
                        (στο Gazebo η βαλίτσα δεν φεύγει ποτέ).
    BODY_IDS          : διαστάσεις των μοντέλων βαλιτσών του Gazebo.

ΑΣΦΑΛΕΙΑ
    Ο έλεγχος σύγκρουσης εδώ ΔΕΝ είναι σύστημα ασφαλείας (Python, μία φορά
    ανά κύκλο). Στον πραγματικό βραχίονα: safety zones στον controller,
    χαμηλές ταχύτητες στο launch, χέρι στο emergency stop.

ΧΑΡΤΗΣ ΑΡΧΕΙΟΥ (με τη σειρά που εμφανίζονται)
    ids tags και ρόλοι χερουλιών -> σταθερές (πρώτα ΡΥΘΜΙΣΕΙΣ ΒΡΑΧΙΟΝΑ) ->
    φόρτωση YAML -> γεωμετρικές συναρτήσεις -> SuitcaseMemory -> TagListener
    -> Mission (παρατήρηση, εμπόδια, ασφάλεια, κίνηση, επιτήρηση, θέσεις
    θέασης, πλευρές, χερούλι, τέλος αναζήτησης, run) -> main
"""
