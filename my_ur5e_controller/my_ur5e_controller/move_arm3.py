#  ΑΙΣΘΗΤΗΡΑΣ  - κόμβος ROS που ακούει τις ανιχνεύσεις και δίνει τη θέση κάμερας
# =============================================================================
class TagListener(Node):
    """Κόμβος ROS: κρατά τις ΤΕΛΕΥΤΑΙΕΣ ανιχνεύσεις tags και τη θέση της κάμερας.

    detections : id -> (x, y, z) στο BASE_FRAME
    quats      : id -> quaternion του tag (πλήρης προσανατολισμός)
    yaws       : id -> στροφή γύρω από z (για τη γεωμετρία της βαλίτσας)
    Κάθε νέο μήνυμα ΑΝΤΙΚΑΘΙΣΤΑ τα προηγούμενα (ό,τι δεν φαίνεται τώρα, λείπει).
    """
    def __init__(self):
        super().__init__('move_arm3_listener')
        self.detections, self.yaws = {}, {}  # id -> (x, y, z) / id -> yaw
        self.quats = {}                     # πλήρης προσανατολισμός tag
        self.create_subscription(MarkerArray, '/luggage/tag_detections', self.cb, 10)
        self.handle_pub = self.create_publisher(
            PoseStamped, '/luggage/handle_pose_final', 10)
        self.co_pub = self.create_publisher(CollisionObject, '/collision_object', 10)
        self.tf_buffer = Buffer()
        self.tf_listener = TransformListener(self.tf_buffer, self)

    def cb(self, msg):
        """Νέο MarkerArray από τον ανιχνευτή -> ενημέρωση detections/quats/yaws."""
        self.detections, self.yaws, self.quats = {}, {}, {}
        for m in msg.markers:
            self.detections[m.id] = (m.pose.position.x, m.pose.position.y,
                                     m.pose.position.z)
            q = m.pose.orientation
            self.quats[m.id] = (q.x, q.y, q.z, q.w)
            self.yaws[m.id] = math.atan2(2.0*(q.w*q.z + q.x*q.y),
                                         1.0 - 2.0*(q.y*q.y + q.z*q.z))

    def camera_position(self):
        """Θέση (x, y, z) του CAMERA_LINK στο BASE_FRAME από το TF, ή None."""
        try:
            t = self.tf_buffer.lookup_transform(
                BASE_FRAME, CAMERA_LINK, Time()).transform.translation
            return (t.x, t.y, t.z)
        except Exception:
            return None

    def publish_handle(self, pos):
        """Δημοσιεύει τη θέση του χερουλιού προορισμού (/luggage/handle_pose_final)."""
        msg = PoseStamped()
        msg.header.frame_id = BASE_FRAME
        msg.header.stamp = self.get_clock().now().to_msg()
        msg.pose.position.x = float(pos[0])
        msg.pose.position.y = float(pos[1])
        msg.pose.position.z = float(pos[2])
        msg.pose.orientation.w = 1.0
        self.handle_pub.publish(msg)


