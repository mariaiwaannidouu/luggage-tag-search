#      ros2 launch my_ur5e_controller run_move_arm3.launch.py \
#           robot_config:=/πλήρες/path/gofa12.yaml
#  Χωρίς robot_config ισχύουν ακριβώς οι τιμές που βλέπεις σε αυτό το αρχείο.
