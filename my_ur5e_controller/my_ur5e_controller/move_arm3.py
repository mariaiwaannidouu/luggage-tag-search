# =============================================================================
# Planning group του MoveIt (όνομα από το SRDF του βραχίονα).
PLANNING_GROUP = 'ur_manipulator'
# TF frame της κάμερας στο άκρο: ΑΥΤΟ το frame μετακινεί ο κώδικας (όχι το tool0).
# Σύμβαση: +X = κατεύθυνση θέασης, +Z = «πάνω» της εικόνας (όχι optical frame).
CAMERA_LINK = 'gemini_camera_link'
# Frame αναφοράς ΟΛΩΝ των συντεταγμένων (ανιχνεύσεις, στόχοι, εμπόδια).
BASE_FRAME = 'base_link'

# UR5e: ονομαστική εμβέλεια 0.85m μέχρι τη φλάντζα. Κρατάμε μικρό περιθώριο
# (0.83) για αποφυγή ιδιομορφιών στο πλήρες τέντωμα, αλλά όχι υπερβολικό -
# το 0.80 έκοβε θέσεις που ο βραχίονας μπορούσε να φτάσει.
# ΠΛΗΡΕΣ ΤΕΝΤΩΜΑ: μετρημένη πραγματική εμβέλεια κάμερας 0.92-0.93m. Με 0.83
# κόβονταν ΠΡΙΝ ρωτηθεί το IK όλες οι ΜΕΤΩΠΙΚΕΣ θέσεις της μακρινής πλευράς
# και έμεναν μόνο οι ξυστές (το tag φαινόταν κάθετα και δεν διαβαζόταν).
# Αν μια θέση δεν φτάνεται, το λέει το IK (έλεγχος ~30ms), όχι αυτό το όριο.
MAX_REACH, MIN_REACH = 0.93, 0.22

# Έλεγχος IK ΠΡΙΝ τον planner. Το "Unable to sample any valid states for goal
# tree" σημαίνει ότι ο στόχος είναι ΑΔΥΝΑΤΟΣ - ο planner όμως το ανακαλύπτει
# μετά από 10s τυχαίας αναζήτησης. Ένα IK check κοστίζει ~1ms.
IK_TIMEOUT = 0.03

# --- ΟΧΙ ΣΒΟΥΡΑ: μικρή κίνηση αρθρώσεων ---
# Το IK ξεκινά από την ΤΩΡΙΝΗ στάση του βραχίονα και, ανάμεσα στις περιστροφές
# της κάμερας (roll), κρατάμε αυτή με τη ΜΙΚΡΟΤΕΡΗ κίνηση αρθρώσεων. Ο planner
# πηγαίνει ΑΚΡΙΒΩΣ σε αυτή τη στάση - την ίδια που ελέγχθηκε για αυτο-απόκρυψη.
# (Παλιά ο planner έλυνε μόνος του το IK για την πόζα και μπορούσε να διαλέξει
#  άλλη διάταξη: ολόκληρη σβούρα και ο βραχίονας μπροστά στην κάμερα.)
# SMALL_MOVE: αν μια λύση κινεί κάθε άρθρωση λιγότερο από αυτό, την κρατάμε
# αμέσως χωρίς να δοκιμάσουμε τις υπόλοιπες περιστροφές.
SMALL_MOVE = math.radians(30)

# --- ΕΛΕΥΘΕΡΟΣ ΠΡΟΣΑΝΑΤΟΛΙΣΜΟΣ ΚΑΜΕΡΑΣ (roll) ---
# Η περιστροφή γύρω από τον ΑΞΟΝΑ ΘΕΑΣΗΣ δεν αλλάζει ΤΙ βλέπει η κάμερα,
# μόνο πώς είναι γυρισμένη η εικόνα - και το ArUco δεν το νοιάζεται
# καθόλου: αναγνωρίζει το tag σε οποιαδήποτε περιστροφή.
# Κρατώντας το roll καρφωμένο στο 0, ο βραχίονας έχανε λύσεις IK σε θέσεις
# απολύτως εφικτές - π.χ. χερούλι στην ΑΠΕΝΑΝΤΙ πλευρά από εκεί που
# στέκεται. Τώρα δοκιμάζονται με σειρά: κανονικά, ανάποδα, πλάγια.
# Κάθε επιπλέον επιλογή κοστίζει ένα IK check (~30ms) ΜΟΝΟ αν οι
# προηγούμενες αποτύχουν, οπότε στη συνήθη περίπτωση δεν κοστίζει τίποτα.
#
# ΠΛΗΡΩΣ ΕΛΕΥΘΕΡΟ ROLL: το μόνο που απαιτείται είναι ο άξονας θέασης να
# περνά από το σωστό σημείο. Η εικόνα μπορεί να είναι γυρισμένη όπως
# να 'ναι, και ανάποδα. Δοκιμάζεται ΚΑΘΕ περιστροφή ανά 30° (12 συνολικά):
# πρώτα οι 0/180/±90 όπως πριν, μετά οι ενδιάμεσες. Χειρότερη περίπτωση
# (καμία δεν φτάνει): 12 x IK_TIMEOUT = 0.36s ανά πόζα, αντί 0.12s.
ROLL_OPTIONS = [math.radians(a) for a in
                (0, 180, 90, -90, 30, -30, 150, -150, 60, -60, 120, -120)]

# --- ΑΠΟΦΥΓΗ ΑΥΤΟ-ΑΠΟΚΡΥΨΗΣ ---
# Ο βραχίονας εκτείνεται από τη ΒΑΣΗ προς την κάμερα. Αν η κάμερα κοιτάει
