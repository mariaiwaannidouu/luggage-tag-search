# --- ΜΝΗΜΗ ΒΑΛΙΤΣΑΣ ---
# Η κατεύθυνση των ροδακιών κρατιέται σε ΤΟΠΙΚΗ γωνία (ως προς τον άξονα της
# βαλίτσας), άρα ΔΕΝ παλιώνει όταν η βαλίτσα γυρίζει: δεν λήγει πια. (Παλιά
# έληγε σε 8s -> ξαναγινόταν ευρύ πλάνο αμέσως μετά το «απέναντι».)
# SEARCH_MEMORY: για πόσο συνεχίζει η αναζήτηση με το 6D pose της μνήμης όταν
#   το body tag δεν φαίνεται (π.χ. κάμερα κολλητά στο πλάι της βαλίτσας).
#   Κάθε νέα θέαση του body tag το ανανεώνει.
SEARCH_MEMORY = 60.0
# Ροδάκια πιο μακριά από αυτό από το κέντρο μιας βαλίτσας δεν είναι δικά της.
